/**
 * Ряд тегов `popover` поделён окончательно — общее для спеков, которые ждут
 * деления ряда (`tags-overflow.spec.ts`, `select-tags.spec.ts`,
 * `tags-variant.spec.ts`).
 *
 * Появление кнопки «…» — ещё не конец замера. Первый проход
 * `TTagsOverflowPlugin` считает без неё: кнопки в разметке ещё нет, и
 * резервировать под неё нечего (`more: undefined` в
 * `plugins/src/custom/tags/overflow/fit.ts`). Кнопка появляется вместе с
 * хвостом, а тег, которому рядом с ней не хватило места, уезжает в панель
 * следующим проходом — когда узел кнопки готов и её ширина известна. До тех
 * пор кнопка стоит за краем ряда, и ряд её обрезает
 * (`themes/oren/src/components/tags/_tags.scss`). Тест, который читал ряд
 * сразу после появления кнопки, ловил этот кадр: кнопка за краем, а в ряду на
 * тег больше, чем в нём останется.
 *
 * Проход с кнопкой резервирует под неё её ширину и зазор (`countFitting`),
 * поэтому кнопка целиком внутри ряда — это деление окончательное, а в
 * промежуточном кадре она всегда снаружи. Условие — то, что обещает плагин,
 * и от числа кадров замера оно не зависит. Ожидание числом кадров записало бы
 * в тест, сколько кадров идёт замер, и молча перестало бы хватать, удлинись
 * его путь.
 *
 * Внутри — с обеих сторон строки: в RTL её конец слева, и кнопка выходит за
 * левый край ряда. Поэтому направление отдельной ветки не требует.
 *
 * Одна копия на всех, как у `focus-ring.ts`: разойдись две, один спек молча
 * ждал бы не того.
 */

import { expect } from 'vitest'

/** Допуск на субпиксельное округление координат. */
const EPSILON = 0.5

/** Ряд `row` поделён окончательно: кнопка «…» в нём есть и целиком лежит в его боксе. */
export const isSplit = (row: Element): boolean => {
	const more = row.querySelector('.s-tags__more')

	if (!more) return false

	const button = more.getBoundingClientRect()
	const box = row.getBoundingClientRect()

	return button.left >= box.left - EPSILON && button.right <= box.right + EPSILON
}

/**
 * Ждёт, пока ряд поделится окончательно (`isSplit`). Ряд — функцией: узел
 * читается заново на каждой попытке.
 */
export const expectSplit = (row: () => Element): Promise<void> =>
	expect.poll(() => isSplit(row()), { message: 'ряд поделён: кнопка «…» внутри ряда' }).toBe(true)
