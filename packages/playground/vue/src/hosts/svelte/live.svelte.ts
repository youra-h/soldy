import { enUS, type TLocale } from '@soldy-ui/plugins'

/**
 * Значение, которое хост меняет снаружи, а корень Svelte читает: присвоение
 * `current` — новая отрисовка корня.
 *
 * `$state.raw`, а не `$state`: значение уходит компонентам как есть, без
 * прокси. Пропсы превью несут экземпляр ядра и движок, локаль заморожена — все
 * они обязаны дойти до компонента теми же объектами, а глубокая реактивность
 * хосту не нужна: оболочка отдаёт пропсы целиком, новым объектом на каждую
 * смену.
 *
 * Руны работают только в `.svelte` и `.svelte.ts`, поэтому ячейка — в своём
 * модуле.
 */
export class TLive<T> {
	current: T

	constructor(value: T) {
		this.current = $state.raw(value)
	}
}

/**
 * Язык шапки — один на все корни хоста. Корень читает его на отрисовке, и
 * смена доходит до провайдера каждого корня без перемонтирования.
 */
export const language = new TLive<TLocale>(enUS)
