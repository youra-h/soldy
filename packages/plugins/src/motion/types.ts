/**
 * Режим движения библиотеки — один на всё приложение (`useMotion`).
 *
 * - `system` — как просит система: настройка «меньше движения» у
 *   пользователя (`prefers-reduced-motion`). Так и без вызова `useMotion` —
 *   это режим по умолчанию;
 * - `full` — движение всегда, о чём бы система ни просила: приложение решило,
 *   что движение ему нужно;
 * - `reduce` — без движения всегда.
 *
 * Движение — смена места, размера, поворота и формы во времени и плавная
 * прокрутка. Цвет, прозрачность и тень — не движение: их режим не трогает.
 */
export type TMotionMode = 'system' | 'full' | 'reduce'
