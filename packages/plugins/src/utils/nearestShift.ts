import type { TInlineSpan, TNearestShiftOptions } from './types'

/**
 * Доводка элемента под фокусом в окно области прокрутки — чистая функция,
 * без DOM: область и её элементы сюда приходят отрезками по строке. Отсюда и
 * проверяемость: субпиксели, элемент шире окна и оба края проверяются
 * числами, а не настоящей раскладкой.
 *
 * Живёт в общих утилитах, а не у ленты: доводят двое — вьюпорт ленты
 * (`TScrollerViewportPlugin`) и ряд тегов `scroll` (`TTagsScrollPlugin`).
 * Своя арифметика у второго разошлась бы с первой: допуск, элемент шире окна
 * и «накрывает окно» пришлось бы писать дважды. У ленты сверх этого есть
 * снап, и он остаётся у неё (`resolveFocusShift`).
 *
 * Направление письма здесь не нужно: ближайший сдвиг одинаков в обе стороны,
 * а сдвиг — физический, как у `scrollBy`.
 */

/**
 * Допуск на субпиксельное округление: край, вышедший из окна на полпикселя, —
 * ещё в окне. Область встаёт на целый пиксель, а края элементов дробные.
 */
const TOLERANCE = 0.5

/**
 * Сдвиги области, при которых отрезок лежит в окне, а если он шире окна —
 * накрывает его: больше окна от него не увидеть. Сдвиг — как у `scrollBy`: на
 * сколько содержимое области уезжает влево.
 */
function fitting(span: TInlineSpan, scrollWindow: TInlineSpan): [number, number] {
	const left = span.left - scrollWindow.left
	const right = span.right - scrollWindow.right

	return [Math.min(left, right), Math.max(left, right)]
}

/**
 * На сколько сдвинуть область, чтобы элемент под фокусом встал в окно, — или
 * `null`, если он уже там.
 *
 * С элементом области (`item`) в окно встаёт и он. Не шире окна — целиком: у
 * тега в ряду кольцо фокуса рисует пилюля, а крестик без подписи не скажет,
 * какой тег он закроет. Шире окна — накрывает его, а элемент под фокусом
 * лежит в окне: так крестик в конце длинного тега виден, хотя начало тега за
 * краем.
 *
 * Из всех таких сдвигов берётся ближайший: область уезжает не дальше, чем
 * нужно, и то, что было в окне, по возможности в нём и остаётся.
 *
 * Элемент под фокусом шире окна в него не встанет ни при каком сдвиге и
 * доводится до ближайшего положения, где накрывает окно: больше окна от него
 * всё равно не увидеть.
 */
export function nearestShift({
	scrollWindow,
	focused,
	item = focused,
}: TNearestShiftOptions): number | null {
	const [focusFrom, focusTo] = fitting(focused, scrollWindow)
	const [itemFrom, itemTo] = fitting(item, scrollWindow)
	const from = Math.max(focusFrom, itemFrom)
	const to = Math.min(focusTo, itemTo)

	if (from - TOLERANCE <= 0 && to + TOLERANCE >= 0) return null

	return Math.min(Math.max(0, from), to)
}
