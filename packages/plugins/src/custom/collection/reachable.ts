import type { IControl } from '@soldy-ui/core'

/**
 * Элемент коллекции, на который можно перевести фокус: не выключен, видим и
 * отрисован. Выключенное поле и скрытый узел фокус не примут, и запись
 * `focused = true` ушла бы в пустоту, хотя рядом есть элемент, который его
 * примет.
 *
 * Правило узла фокуса для коллекций, у которых своей остановки в модели нет:
 * у секций Accordion остановок столько же, сколько заголовков, а остановку
 * радио выбирает браузер. Где остановка в модели есть — у табов и тегов, —
 * правило той же формы держит расширение коллекции (`isEnabledTab`,
 * `isEnabledTag`), и копии здесь у него нет.
 */
export function isReachable(item: Pick<IControl, 'disabled' | 'visible' | 'rendered'>): boolean {
	return !item.disabled && item.visible && item.rendered
}
