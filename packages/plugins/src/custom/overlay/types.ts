import type { TCloseReason } from '@soldy-ui/core'

/** Опции привязки плагина оверлея к открытости владельца. */
export interface IOverlayOpenOptions {
	/**
	 * Свойство инстанса, которым выражена открытость.
	 *
	 * `null` отключает привязку: плагин не узнаёт об открытии и не закрывает
	 * владельца. По умолчанию `open` — так открытость называют и `TPopover`,
	 * и `TSelect`. У модального окна открытость — `visible`: оно само и есть
	 * слой.
	 */
	property?: string | null

	/** Событие, по которому плагин перечитывает открытость. */
	event?: string
}

/**
 * Открытость владельца глазами плагина оверлея: прочитать, записать и
 * отвязаться.
 */
export interface IOverlayOpenState {
	/** Открыт ли владелец сейчас. */
	read(): boolean
	/**
	 * Записать открытость владельцу. Так оверлей закрывает сам себя, когда
	 * закрытие — не решение пользователя: Tab увёл фокус из панели Popover.
	 */
	write(value: boolean): void
	/**
	 * Пользователь закрывает владельца — нажатием мимо или Escape. Владельца,
	 * который принимает запрос (`requestClose`), плагин закрывает запросом с
	 * причиной: закрыться ли, решает он сам. Остальных — записью, как `write`.
	 */
	close(reason: TCloseReason): void
	/**
	 * Снять подписку на открытость с шины владельца: `onChange` привязки
	 * больше не зовётся. Плагин зовёт это в `destroy()` — владелец переживает
	 * плагин, когда приложение передаёт свой `ctrl`.
	 */
	unbind(): void
}
