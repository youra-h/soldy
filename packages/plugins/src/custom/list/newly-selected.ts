/**
 * Элемент, за которым список следует после смены выбора, — тот, что стал
 * выбранным: первый из выбранных (`selected`, по порядку выбора), чья отметка
 * сменилась (`changed` — второй аргумент `change:selection`). `undefined` —
 * выбранным не стал никто: выбор сняли или только переставили, и следовать не
 * за чем.
 *
 * Не первый выбранный: в `multiple` выбранных несколько, и выбор клавишей или
 * кликом уводил бы подсветку и прокрутку к первому из них, а не к элементу,
 * который выбрали сейчас. В `single` выбранный один — он и стал выбранным.
 * Значение снаружи — по тому же правилу: список встаёт на новый выбранный.
 *
 * Одно на клавиатуру ListBox (`TListKeyboardPlugin`) и прокрутку списка
 * (`TListScrollPlugin`): элемент оба ищут одним правилом, и подсветка не
 * встанет на одном элементе, пока прокрутка уезжает к другому.
 */
export function newlySelected<TItem>(
	selected: readonly TItem[],
	changed: ReadonlySet<TItem>,
): TItem | undefined {
	return selected.find((item) => changed.has(item))
}
