import type { TPluginEvents } from '../../../base'

/**
 * Своих событий у плагина нет: результат жеста виден через владельца —
 * `swiping`, закрытие с причиной `swipe` и его `close:before`. Второй путь к
 * тем же фактам через события плагина разошёлся бы с первым.
 */
export type TDrawerSwipePluginEvents = TPluginEvents

/** Ось, вдоль которой панель уезжает к своему краю. */
export type TDrawerSwipeAxis = 'x' | 'y'

/**
 * Нажатие, которое ещё не стало жестом: жест начнётся, когда указатель уйдёт
 * от точки нажатия вдоль оси панели дальше порога.
 */
export type TDrawerSwipePress = {
	/** `pointerId` нажатия: чужие указатели его не двигают */
	pointer: number
	/** Точка нажатия в координатах окна */
	x: number
	y: number
}

/** Точка пути жеста — по ней считается скорость в конце. */
export type TDrawerSwipeSample = {
	/** Время события, мс */
	time: number
	/** Путь к краю от точки нажатия, px; назад от края — со знаком минус */
	distance: number
}

/** Жест, который ведёт плагин: от начала до отпускания. */
export type TDrawerSwipeGesture = {
	/** `pointerId` указателя жеста */
	pointer: number
	/** Ось панели — на весь жест, вычислена в начале */
	axis: TDrawerSwipeAxis
	/**
	 * Куда по оси окна панель уезжает к своему краю: `1` — к большим
	 * координатам (вправо, вниз), `-1` — к меньшим. `start` и `end` — с учётом
	 * вычисленного направления письма.
	 */
	sign: 1 | -1
	/** Координата нажатия по оси */
	origin: number
	/** Размер панели по оси: доля пути считается от него */
	size: number
	/** Сдвиг панели к краю, px; за открытое положение — с сопротивлением, минус */
	offset: number
	/** Недавние точки пути — окно скорости */
	samples: TDrawerSwipeSample[]
	/** Инлайновые `user-select` корня до жеста — вернуть в конце */
	userSelect: readonly [property: string, value: string][]
}
