import type { TMenuPoint } from '@soldy-ui/core'

/**
 * Срез плагина открытия, который видят стратегии: что они делают с меню.
 *
 * Стратегия знает свои события на корне, а не меню и не соседние плагины:
 * открывает, переставляет и закрывает она через плагин, и подсветку при
 * открытии клавишей решает он.
 */
export interface IMenuOpenHost {
	/** Открыто ли меню. */
	readonly isOpen: boolean
	/** Переключить меню — нажатие кнопки. */
	toggle(): void
	/**
	 * Вызвать меню у точки окна, открытое — переставить к ней. Вызвали
	 * клавишей (`byKeyboard`) — подсвечен первый пункт, и фокус на нём, как у
	 * кнопки с клавиатуры; указателем — фокус на панели.
	 */
	invoke(point: TMenuPoint, byKeyboard: boolean): void
	/** Закрыть меню. */
	close(): void
}

/**
 * Способ открытия меню на его корне — по стратегии на режим `openOn`. Живёт,
 * пока не сменились режим или корень: слушатели ставит конструктор, снимает
 * `destroy()`.
 */
export interface IMenuOpenStrategy {
	/** Снять слушатели корня и отменить отложенное. */
	destroy(): void
}

/** Конструктор стратегии: плагин заводит её на корень по режиму владельца. */
export type TMenuOpenStrategyCtor = new (root: Element, host: IMenuOpenHost) => IMenuOpenStrategy

/**
 * Нажатие пальцем или пером в области контекстного меню, которое ещё не
 * решено: долгое — вызов, короткое у открытого меню — закрытие, ушедшее
 * дальше порога — прокрутка, и ни то ни другое.
 */
export type TMenuContextPress = {
	/** `pointerId` нажатия: чужие указатели его не решают */
	pointerId: number
	/** Точка нажатия в координатах окна — у неё встанет меню */
	x: number
	y: number
	/** Короткое нажатие закроет меню: оно было открыто, и вызовом нажатие не стало */
	closes: boolean
	/** Таймер долгого касания; `null` — не ждём: своего вызова нет или он был */
	timer: ReturnType<typeof setTimeout> | null
}
