import type { IPluginContext, TPluginEvents } from '../../base'

/**
 * События взаимодействия с пользователем.
 *
 * Разделены намеренно: `click` — то, что реально произошло в DOM, `press` —
 * намерение активировать контрол. Они не совпадают. У нативной `<button
 * disabled>` клик не приходит вообще, а у `<div aria-disabled="true">` —
 * приходит. `press` сглаживает это, `click` оставляет как есть — иначе с
 * инстанса не добраться до правды. Enter и пробел на корне-`<div>` плагин
 * превращает в клик сам, как браузер у `<button>`, поэтому `press` всегда
 * приходит из клика.
 */
export type TActionPluginEvents = TPluginEvents & {
	/**
	 * Активация контрола: клик — мышью или из Enter/Space с фокусом на корне.
	 * Не приходит на disabled.
	 */
	press: (event: MouseEvent) => void

	/** Сырой DOM-клик, без фильтра по disabled. */
	click: (event: MouseEvent) => void

	/** Фокус внутри корневого элемента. */
	focus: (event: FocusEvent) => void

	/** Фокус ушёл из корневого элемента. */
	blur: (event: FocusEvent) => void
}

/**
 * Правило узла фокуса: по корню компонента и контексту его набора находит
 * узел внутри корня, который держит фокус компонента, — поле формы, узел
 * списка, таб-остановку. `null` — такого узла нет, и фокус получает корень.
 *
 * Модель фокуса у каждого компонента своя, и знают её плагины компонента.
 * Поэтому правило — функция слоя плагинов рядом с теми, кто этот узел уже
 * ищет (`fieldOf`, `listOf`, `tabStopOf`), а называет его дескриптор
 * компонента опцией плагина действия.
 */
export type TFocusTarget = (root: Element, ctx: IPluginContext) => Element | null

export interface IActionPluginOptions {
	/**
	 * Клавиши, активирующие контрол с фокусом на корне не-нативного тега.
	 * По умолчанию Enter и Space — как требует WAI-ARIA для role="button".
	 */
	keys?: readonly string[]

	/**
	 * Куда ставят фокус запись `focused = true` и `focus()` — правило узла
	 * фокуса: `ActionPluginDescriptor.with({ focusTarget: listOf })`. Без
	 * правила, и когда оно вернуло `null`, фокус получает корень.
	 *
	 * Нужна компоненту, у которого фокус держит не корень: у поля — вложенный
	 * `<input>`, у ListBox — узел списка рядом с шапкой и подвалом, у Tabs —
	 * таб-остановка. Общего правила «первая остановка Tab внутри» нет: кнопка
	 * в слоте `leading` и поле поиска в шапке — свои остановки перед главной
	 * частью, и фокус ушёл бы на них.
	 */
	focusTarget?: TFocusTarget
}
