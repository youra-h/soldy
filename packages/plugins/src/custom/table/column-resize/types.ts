import type { TPluginEvents } from '../../../base'

/**
 * Своих событий у плагина нет: результат жеста и клавиш виден через колонку —
 * ширину, `data-resizing` и `commit` сообщает она, а таблица отдаёт наружу
 * `column:resize`. Второй путь к тем же фактам через события плагина
 * разошёлся бы с первым.
 */
export type TTableColumnResizePluginEvents = TPluginEvents

export interface ITableColumnResizePluginOptions {
	/**
	 * Шаг стрелки и жеста скринридера, px. По умолчанию — 10: заметно глазу и
	 * не требует десятков нажатий, чтобы сдвинуть колонку на слово.
	 */
	step?: number
	/**
	 * Крупный шаг — Shift со стрелкой, PageUp и PageDown, px. По умолчанию —
	 * 100, десять шагов, как крупный шаг ползунка.
	 */
	largeStep?: number
}

/** Жест, который ведёт плагин: от нажатия до отпускания. */
export type TTableColumnResizeGesture = {
	/** `pointerId` указателя жеста: чужие указатели его не двигают */
	pointer: number
	/** Точка нажатия по строке — `clientX` */
	origin: number
	/**
	 * Знак роста ширины по оси окна: `1` — вправо, `-1` — влево. Ручка стоит у
	 * конца строки, и в RTL колонку расширяет движение влево. Вычислен при
	 * нажатии — на весь жест
	 */
	sign: 1 | -1
	/**
	 * Сдвиг призрака, px по оси окна, который плагин записал последним, —
	 * только в отложенном жесте: тот же сдвиг второй раз не пишется
	 */
	ghost: number | undefined
}
