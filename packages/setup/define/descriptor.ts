/**
 * defineDescriptor — дескриптор компонента строится один раз, а не на каждое монтирование.
 *
 * Фабрика дескриптора ленива намеренно: дескрипторы ссылаются друг на друга
 * через `extends`, и у коллекций эти ссылки образуют цикл, который на уровне
 * модулей не развязать. Но результат от вызова к вызову один и тот же:
 * декларации собираются из contribution и родителя, умолчания — из статики
 * класса ядра, и ничего из этого после сборки не меняется.
 *
 *   export const ButtonDescriptor = defineDescriptor(() =>
 *     defineComponent({ ctor: TButton, extends: TextableDescriptor(), … }),
 *   )
 *
 * До этого `ButtonDescriptor()` на каждом монтировании пересобирал всю цепочку
 * до `EntityDescriptor`, а адаптеры зовут фабрику дважды: при импорте модуля
 * компонента (статические пропсы и события) и в `setup` на каждое монтирование.
 * Теперь оба вызова получают один объект, и у дескриптора появляется
 * устойчивая идентичность — по ней кэшируются состав и его публичная
 * поверхность.
 */
export function defineDescriptor<T extends object>(build: () => T): () => T {
	let descriptor: T | undefined

	return () => (descriptor ??= build())
}
