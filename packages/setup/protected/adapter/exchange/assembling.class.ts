/**
 * TAssembling — сборка над инстансом атомарна для остальных его монтирований.
 *
 * Над одним инстансом бывает больше одного монтирования: `ctrl` снаружи
 * переехал в другое место дерева, и фреймворк собирает новый компонент, пока
 * прежний ещё не снят. Сборка пишет в инстанс — начальные значения внешнему
 * `ctrl`, `id` плагинов связок от нового монтирования, — и прежнее
 * монтирование слышит каждую запись, пока сборка ещё идёт. Фреймворк, который
 * собирает компонент на рендере, получил бы обновление чужого компонента
 * посреди этого рендера, а повтор рендера (`Suspense`) — новую запись и новое
 * обновление на каждый повтор.
 *
 * Поэтому, пока над инстансом идёт сборка (`run`), обмены остальных
 * монтирований копят его состояние и уведомления и выпускают их одной
 * микрозадачей после сборки (`defer`, правило выпуска — `TExchange`): итог, а
 * не каждый шаг. Микрозадача не вклинивается в тело рендера, а граница тишины
 * — сама сборка, синхронно: от того, примет ли сборку фреймворк, тишина не
 * зависит, и сборка, которую он выбросил, её не держит.
 *
 * Отменяемые события (`*:before`) тишина не задерживает: это вопрос, ответ на
 * который нужен сейчас, и `preventDefault` приёмника прежнего монтирования
 * отменяет запись сборки, как вне её.
 *
 * Механика одна на все адаптеры и включена всегда: у инстанса с одним
 * монтированием копить в тишине некому, и стоит она одну проверку `WeakMap`
 * на событие.
 */

export class TAssembling {
	/** Сколько сборок идёт над инстансом: сборка вправе собрать вложенную над тем же. */
	private readonly _depth = new WeakMap<object, number>()

	/** Собрать над инстансом: на время `build` состояние остальных монтирований молчит. */
	run<T>(instance: object, build: () => T): T {
		this._depth.set(instance, (this._depth.get(instance) ?? 0) + 1)

		try {
			return build()
		} finally {
			const depth = (this._depth.get(instance) ?? 1) - 1

			if (depth > 0) this._depth.set(instance, depth)
			else this._depth.delete(instance)
		}
	}

	/** Над кем-то из владельцев идёт сборка. */
	covers(owners: readonly object[]): boolean {
		return owners.some((owner) => this._depth.has(owner))
	}

	/** Перечитать после сборки: одной микрозадачей, вне тела, которое сейчас выполняется. */
	defer(reread: () => void): void {
		queueMicrotask(reread)
	}
}

/** Сборки процесса — общие для всех адаптеров, как и инстансы, над которыми они идут. */
export const assembling = new TAssembling()
