/**
 * withParts — составной компонент: `<Tabs.Item>` рядом с `<Tabs>`.
 *
 * Точка — основная форма записи для составных компонентов. Она решает проблему
 * плоских имён: `Tabs` + `TabsItem` + `TabsContent` приходится держать
 * согласованными вручную, а `Tabs.Item` / `Tabs.Content` согласованы по
 * построению — префиксом служит сам владелец.
 *
 * Плоские имена продолжают экспортироваться: они нужны там, где точки нет
 * (Angular, Web Components) и как запасной путь импорта.
 *
 *   export const Tabs = withParts(TabsComponent, { Item: TabsItem, Content: TabsContent })
 *
 *   <Tabs><Tabs.Item /></Tabs>       // основная форма
 *   <Tabs><TabsItem /></Tabs>        // то же самое
 *
 * **Ограничение Vue.** Точка резолвится только компилятором SFC, который видит
 * импорт как биндинг области видимости. В строковом `template` с регистрацией
 * через `components: {}` рантайм-компилятор ищет `Tabs.Item` как имя в реестре,
 * не находит и молча рендерит пустоту.
 *
 * Владелец мутируется намеренно, а не копируется: копия — другой объект, и
 * идентичность компонента (keep-alive, devtools, сравнение типов) разъехалась
 * бы с тем, что экспортирует сам файл компонента.
 *
 * Частью становится не любой узел разметки, а только то, у чего есть
 * собственная идентичность — сущность в ядре, состояние или `id` для
 * ARIA-связки. Всё остальное остаётся слотом (см. AGENTS.md).
 */
export function withParts<TOwner extends object, TParts extends Record<string, unknown>>(
	owner: TOwner,
	parts: TParts,
): TOwner & TParts {
	return Object.assign(owner, parts)
}
