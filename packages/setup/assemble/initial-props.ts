/**
 * Начальные значения пропсов — один раз, при сборке компонента.
 *
 * Пропсы фреймворк отдаёт в сборку при создании контекста, во всех шести
 * адаптерах. Здесь они и применяются, для любого инстанса одинаково. Кому
 * писать, решает сборка (`assembleComponent`, `IComponentPlugins`):
 *
 * - свой инстанс получил пропсы ядра конструктором (`new ctor(props)`) — их
 *   второй раз не пишем: сеттер коллекции `items` пересоздал бы элементы;
 * - внешний `ctrl` собран без этих пропсов — пишем в него;
 * - плагины создаются после инстанса и пропсов не видят — пишем в них.
 *
 * Как писать, решает само свойство (`TProperty.initialize`): значение, равное
 * умолчанию декларации, ничего не задаёт — так внешний `ctrl` сохраняет своё
 * состояние, даже если фреймворк подставил умолчание за автора (Vue делает это
 * с каждым пропом, у которого объявлен `default`). Запись идёт сеттером, он сам
 * эмитит триггер. Фреймворк берёт начальное состояние подпиской на связку,
 * дальше его обновляют только триггеры — второй стартовой записи из адаптера
 * нет.
 *
 * Имена — те же, что у поверхности (`propValueOf`): `aria_label` во всех
 * фреймворках, и сырое `label` для headless-кода и тестов.
 */

import type { TProperty } from '@soldy/accessor'
import { propValueOf } from '../naming'

export function applyInitialProps(
	properties: readonly TProperty[],
	props: object | undefined,
): void {
	if (!props) return

	for (const property of properties) property.initialize(propValueOf(props, property.name))
}
