<template>
	<!--
		Подпись контрола. Корень — `label`: программист рисует его по `tag`
		(`<component :is="tag">`, по умолчанию `label`). Модификаторы
		`s-label--position-*`, `s-label--size-*` и `s-label--variant-*` —
		здесь, на корне: тема читает всё отсюда.

		Связки через `for` и `id` нет: контрол — первый labelable-потомок
		`label`, поэтому клик по тексту переключает его, а текст становится
