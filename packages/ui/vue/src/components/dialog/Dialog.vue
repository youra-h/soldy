<template>
	<teleport to="body">
		<!--
			Окно телепортировано в `body` целиком: подложка и панель — соседи, а
			не обёртка и содержимое. Подложка стоит в DOM раньше панели: слой у
			них один (одно число `z-index` инлайном), и панель рисуется поверх
			просто порядком.

			Подложка обязательна и закрывает весь экран: фон под окном скрыт
			от скринридера, но не от указателя, и к странице его не пускает
			только она. Нажатие по ней для плагинов слоя — нажатие мимо корня.
		-->
		<div class="s-dialog__backdrop" />

		<!--
			Корень — сама панель: на ней слой (`data-layer`), пометка
			владельцем, место (`s-dialog--placement-*`), размер
			(`--dialog-width`, `--dialog-height`) и `data-maximized`.
			`tabindex="-1"` — фокус встаёт на саму панель, когда внутри нечего
			фокусировать.

			Порядок в DOM — заголовок, тело, подвал, потом кнопки. В строку
			заголовка кнопки переносит тема, областями сетки. Поэтому фокус
			при открытии попадает на первый контрол содержимого, а не на
			«развернуть», а крестик остаётся последней остановкой Tab.
			Обёртки, которая собрала бы заголовок с кнопками, нет: она вернула
			бы кнопки в начало.
		-->
		<div class="s-dialog" tabindex="-1">
			<!--
				Заголовок рисуется всегда: на него окно ссылается
				`aria-labelledby`. Вокруг слота нет пробелов: пустой заголовок
				тема сворачивает по `:empty`.
			-->
			<h2 class="s-dialog__title"><slot name="title" /></h2>

			<!-- Тело — прокручивается оно, шапка и подвал остаются на месте -->
			<div class="s-dialog__body">
				<slot />
			</div>

			<!-- Подвал — ряд действий. Пустой тема сворачивает по `:empty` -->
			<div class="s-dialog__footer"><slot name="footer" /></div>

			<!--
				Кнопка разворота. Иконок две, видна одна — по состоянию
				окна, как отметка у CheckBox: «развернуть», пока окно не
				развёрнуто, и «вернуть размер» — когда развёрнуто.
			-->
			<Button class="s-dialog__maximize">
				<slot name="maximize-icon">
					<Icon />
				</slot>
				<slot name="restore-icon">
					<Icon />
				</slot>
			</Button>

			<!-- Кнопка закрытия — в углу шапки со стороны конца строки -->
			<Button class="s-dialog__close">
				<slot name="close-icon">
					<Icon />
				</slot>
			</Button>
		</div>
	</teleport>
</template>
