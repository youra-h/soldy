<template>
	<nav class="so-pagination">
		<!--
			Pagination — ряд в одну строку: стрелка «назад», список страниц,
			стрелка «вперёд». Корень — `nav`: ориентир для скринридера, имя — из
			локали («Страницы»), его пишет плагин имён. Код выпустит на корне
			модификаторы `--size-*` и `--variant-*` и `data-disabled`.

			Стрелки стоят вне списка: в списке только страницы и пропуски.
			Отдельных кнопок «в начало» и «в конец» нет — их роль играют первая
			и последняя страницы, они видны всегда.
		-->

		<!--
			Стрелка «назад» — на предыдущую страницу. Код выпустит: `size` и
			`variant` владельца, `disabled` на первой странице и у выключенного
			компонента, имя из локали («Предыдущая страница»). Вида нет: `plain`
			и квадрат даёт тема по контексту. Иконка — роль `arrowRight`, у обеих
			стрелок: «назад» тема зеркалит по направлению строки. Слот
			`prev-icon` — своя иконка; в слот кладут стрелку, которая смотрит в
			конец строки, — тема зеркалит и её.
		-->
		<Button class="so-pagination__prev">
			<slot name="prev-icon">
				<Icon />
			</slot>
		</Button>

		<ol class="so-pagination__list">
			<!--
				Страницы и пропуски — по порядку окна: первая страница, пропуск,
				N страниц вокруг текущей, пропуск, последняя (`1 … 4 5 6 … 10`).
				Страница — элемент коллекции, по одному на каждую показанную; в
				коллекции только страницы окна. Пропуск — разметка владельца там,
				где между соседними страницами окна есть пропущенные, даже одна.

				Слот страницы пробрасывается целиком: `item`, scope — scope слота
				страницы плюс сама страница.
			-->
			<PaginationItem>
				<template #default><slot name="item" /></template>
			</PaginationItem>

			<!--
				Пропуск — не кнопка и не иконка: на нём ничего не нажимают, и
				фокуса у него нет. Многоточие — текстом. Клетку той же ширины, что
				узкая страница, даёт тема.
			-->
			<li class="so-pagination__ellipsis">…</li>
		</ol>

		<!--
			Стрелка «вперёд» — на следующую страницу; `disabled` — на последней.
			Остальное — как у «назад», имя из локали («Следующая страница»),
			слот — `next-icon`.
		-->
		<Button class="so-pagination__next">
			<slot name="next-icon">
				<Icon />
			</slot>
		</Button>
	</nav>
</template>
