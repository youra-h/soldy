<template>
	<th class="s-table-column">
		<!--
			Заголовок колонки — Table.Column. Корень — сама ячейка шапки, рисуется
			по `tag` колонки (по умолчанию `th`). На ней наборы колонки: `aria-sort`
			(только у первой по приоритету — по ARIA его ставят одному заголовку),
			`data-sort` и `data-sort-priority` (пишет расширение сортировки),
			`data-align`, — и ширина переменной `--s-table-column-width`: тема
			кладёт её в ширину ячейки шапки, и по ней раскладка таблицы режет
			колонку.

			Содержимое — одно из двух, по `sortable` колонки.
		-->

		<!--
			Сортируемая колонка — кнопка в заголовке, как в APG Sortable Table:
			Button (`embedded: 'table.sort'`), нажатие — команда коллекции
			`toggleSort(field)`. Вида разметка ей не передаёт: красит её тема по
			контексту (`:where(.s-table-column__sort)`). Выключена вместе с
			таблицей: сортировать её строки нельзя.

			Текст — слот по умолчанию со scope `{ text }`, пустой — `text` колонки;
			таблица отдаёт в него свой слот `header`. Содержимое внутри кнопки: её
			имя — текст заголовка.

			Отметка направления — в слоте кнопки `trailing`, после текста: иконка
			роли `arrowUpward`. Обёртка отметки скрыта от скринридера
			(`aria-hidden`, ставит код): направление он объявляет по `aria-sort`
			заголовка. Отметка стоит и у неотсортированной колонки, невидимой:
			держит место, и текст не сдвигается, когда колонку отсортируют. Вниз
			стрелку поворачивает тема, номер приоритета при сортировке по
			нескольким колонкам дописывает тоже она — у обёртки отметки.
		-->
		<Button class="s-table-column__sort">
			<slot />

			<template #trailing>
				<span class="s-table-column__sort-icon">
					<Icon />
				</span>
			</template>
		</Button>

		<!--
			Несортируемая колонка — только текст заголовка, тот же слот по
			умолчанию. Обёртка — для темы: выключенная таблица гасит текст, а
			кнопку гасит сама кнопка.
		-->
		<span class="s-table-column__text">
			<slot />
		</span>
	</th>
</template>
