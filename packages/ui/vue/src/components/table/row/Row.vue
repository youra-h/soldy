<template>
	<tr class="s-table-row">
		<!--
			Строка таблицы — Table.Row. Корень — `tr`, рисуется по `tag` строки. На
			нём модификаторы размера и варианта (их строке диктует таблица) и набор
			`dataset`: `data-selected` (пишет выбор коллекции — всем строкам) и
			`data-disabled`. Наведения у строки нет: в роли `table` нажатие по
			строке ничего не делает, выбирают чекбоксом.
		-->

		<!--
			Ячейка колонки выбора — только пока режим выбора строк не `none`, как
			её заголовок в шапке. Чекбокс строки — CheckBox
			(`embedded: 'table.select'`) над `selected` строки, выключен вместе со
			строкой. Имя — ссылка на заголовок строки (`aria-labelledby` на `id`
			ячейки колонки `rowHeader`), `id` пишет плагин связок от монтирования.
		-->
		<td class="s-table-row__select">
			<CheckBox />
		</td>

		<!--
			Ячейка — по одной на ячейку строки (`cells`), ключ — колонка. Набор
			ячейки — `data-align` колонки.

			Ячейка колонки `rowHeader` — заголовок строки: `th` с `scope="row"`, на
			её текст ссылается имя чекбокса строки. Остальные — `td`. Класс один:
			тема различает их тегом.

			Содержимое — слот `cell` со scope `{ column, value }`, пустой — `value`
			текстом; таблица отдаёт в него свой слот `cell`, добавив строку.
		-->
		<th class="s-table-row__cell" scope="row">
			<slot name="cell" />
		</th>

		<td class="s-table-row__cell">
			<slot name="cell" />
		</td>
	</tr>
</template>
