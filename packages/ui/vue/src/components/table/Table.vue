<template>
	<table class="s-table">
		<!--
			Table — таблица по паттернам APG Table и Sortable Table. Корень — сама
			`table`, рисуется по `tag`: роль `table` даёт тег, своей клавиатуры у
			таблицы нет (Grid — отдельный режим). Имя таблице — `aria_label` или
			`aria_labelledBy`.

			Разметка статическая: размер и вариант (`--size-*`, `--variant-*`),
			`data-disabled`, `dir`, наборы ARIA и обработчики приходят кодом, здесь
			только состав и имена классов.

			Колонка, строка и ячейка здесь — по одной, как образец перебора:
			заголовки — показанные колонки коллекции (`shownColumns`), строки —
			показанные строки (`shown`: в порядке сортировки), ячейки — ячейки строки
			(`cells`). Колонки задаются только данными (`columns`), строки — только
			данными (`items`): частей разметкой у таблицы нет, поэтому и слота по
			умолчанию нет.
		-->

		<thead class="s-table__head">
			<tr class="s-table__head-row">
				<!--
					Заголовок колонки выбора — первая ячейка шапки. Колонка выбора есть,
					только пока режим выбора строк не `none`: один факт решает и выбор, и
					колонку. Это разметка таблицы, а не колонка коллекции: запись
					`columns` сверкой по `field` её бы удалила.

					В `multiple` в ней чекбокс «выбрать все показанные» — CheckBox
					(`embedded: 'table.select-all'`). Отметку и «часть» он берёт готовыми
					значениями ядра от `shownSelection` (`all` — отмечен, `some` —
					`indeterminate`), действие — команды `selectShown` и
					`deselectShown`. Имя — пропом таблицы, английским по умолчанию: своего
					текста у ячейки нет. В `single` выбирать все нечего, и ячейка пуста —
					она только держит колонку.
				-->
				<th class="s-table__select">
					<CheckBox />
				</th>

				<!--
					Заголовок колонки — Table.Column над экземпляром колонки, по одному на
					показанную колонку, ключ — колонка. Содержимое заголовка — слот
					`header` со scope `{ column }`: колонку выбирают условием по
					`column.field`. Без него — текст колонки.
				-->
				<TableColumn>
					<slot name="header" />
				</TableColumn>
			</tr>
		</thead>

		<tbody class="s-table__body">
			<!--
				Строка — Table.Row над элементом коллекции строк, по одной на
				показанную строку, ключ — строка. Содержимое ячейки — слот `cell` со
				scope `{ row, column, value }`: колонку выбирают условием по
				`column.field`, `value` — поле записи под ключом колонки. Без него —
				`value` текстом.
			-->
			<TableRow>
				<slot name="cell" />
			</TableRow>

			<!--
				Пустое состояние — пока показанных строк нет: строка с одной ячейкой
				на всю ширину таблицы. `colspan` — число показанных колонок вместе с
				колонкой выбора, готовым значением ядра: посчитанное в разметке
				повторилось бы в каждом адаптере. Содержимое — слот `empty`; без него
				ячейка пуста, и под шапкой остаётся пустая полоса — таблица без строк
				не схлопывается в одну шапку.
			-->
			<tr class="s-table__empty-row">
				<td class="s-table__empty">
					<slot name="empty" />
				</td>
			</tr>
		</tbody>
	</table>
</template>
