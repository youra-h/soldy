<template>
	<span class="s-slider">
		<!--
			Ползунок: ручки на рельсе, заливка и метки. Корень рисуется по `tag`,
			по умолчанию `span`: ползунок кладут в подпись `Label`, а внутри
			`label` HTML разрешает только строчную разметку. Поэтому и всё
			внутри — `span`.

			Разметка статическая: ориентация, размер, вариант (`--horizontal` /
			`--vertical`, `--size-*`, `--variant-*`, `--readonly`), состояния
			(`data-disabled`, `data-dragging`), `dir` и обработчики приходят
			кодом, здесь только состав и имена классов. Нажатия и протяжку ловит
			плагин указателя на корне, клавиши — плагин клавиатуры на полях.

			Ручки и метки — разметка, а не компоненты: потребитель их не
			адресует, число ручек задаёт значение, число меток — шкала. Здесь
			каждой по одной как образец перебора.
		-->

		<!--
			Дорожка — ход центров ручек: 0 % и 100 % значения — края её коробки по
			оси, её мерит плагин указателя. Рельс рисует тема псевдоэлементом,
			своего узла у него нет.
		-->
		<span class="s-slider__track">
			<!--
				Заливка — одна на ползунок: от начала или от заданного значения до
				ручки, у двух ручек — между ними. Края приходят переменными в
				`style` (`--s-slider-range-start`, `--s-slider-range-end`).
			-->
			<span class="s-slider__range"></span>

			<!--
				Метки — только если они заданы: шагом или списком значений. Каждая
				метка — позиция в `style` (`--s-slider-position`) и состояния
				`data-in-range` и `data-current`.
			-->
			<span class="s-slider__marks">
				<span class="s-slider__mark">
					<!--
						Подпись — слот `mark` со scope метки. Вокруг слота нет
						пробелов: пустую подпись тема прячет по `:empty`, и метка
						остаётся одной точкой.
					-->
					<span class="s-slider__mark-label"><slot name="mark" /></span>
				</span>
			</span>

			<!--
				Ручка — по одной на значение: позиция в `style`
				(`--s-slider-position`), состояние `data-dragging`.
			-->
			<span class="s-slider__thumb">
				<!--
					Нативное поле — по одному в ручке. Мобильные скринридеры
					двигают его своим жестом, `name`, `disabled` и отправку формы
					даёт браузер, ARIA-дублей им нет. Тема делает его прозрачным
					во всю ручку и не пускает к нему указатель: тянет плагин, а не
					браузер.
				-->
				<input class="s-slider__input" type="range" />
				<!-- Место под подсказку со значением: слот `thumb` со scope ручки. -->
				<slot name="thumb" />
			</span>
		</span>
	</span>
</template>
