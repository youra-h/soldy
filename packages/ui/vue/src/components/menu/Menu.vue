<template>
	<span class="so-menu">
		<!--
			Корень — обёртка триггера и якорь панели, как у Popover: по
			умолчанию `span`, чтобы меню вставало и в строку текста, и в ряд
			кнопок. Панель телепортирована, поэтому в корне лежит только
			триггер, и прямоугольник корня — прямоугольник триггера.

			`data-open` — на корне, для потребителя, который красит свой
			триггер по контексту. Тема меню его не читает: «нажат» открытый
			триггер и так, по `data-selected` из `triggerDataset`.
		-->

		<!--
			Триггер — кнопка потребителя («…», «Действия»). Лежит внутри
			корня: нажатие по открытому триггеру — нажатие внутри владельца, и
			панель не мигает. Своего экземпляра у содержимого слота нет,
			поэтому сторону связки (`aria-haspopup`, `aria-expanded`,
			`aria-controls`) и вид «нажата» (`data-selected`) он получает через
			scope — `triggerAria` и `triggerDataset`, как у Popover. Стрелку у
			кнопки рисует потребитель.
		-->
		<slot name="trigger" />

		<!--
			Панель — Frame: телепорт, слой, привязка к корню (`TAnchorPlugin`,
			отступ 4px, как у Select) и пометка владельцем для закрытия по
			нажатию мимо. Открытость — `visible` панели, а не `rendered`:
			пункты входят в коллекцию при монтировании, и закрытие не должно
			её вычищать. Проявление и исчезание тема читает с `data-open`,
			который Frame пишет сам.

			Сверх своего класса панель несёт размер и вариант меню
			модификаторами — `so-menu__panel--size-<v>` и
			`so-menu__panel--variant-<v>`: модификаторы корня до
			телепортированной панели не доходят, а размер подписей групп и цвет
			пунктов без своего варианта тема берёт с неё.
		-->
		<Frame class="so-menu__panel">
			<!--
				Список — контейнер с ролью `menu` и то, что прокручивается.
				Своим узлом, а не самой панелью: панель — слой и его раскладка,
				список — то, что видит скринридер, как у Select.
			-->
			<div class="so-menu__list">
				<slot>
					<!--
						Пункты из `items` — только действия. Петля — по тому, что
						рисует коллекция (`drawn`), ключ — ключ записи, как у
						ListBox. Слоты пункта пробрасываются целиком: у каждого
						есть `item-<слот>`, scope — scope слота пункта плюс сам
						пункт (`item`).
					-->
					<MenuItem>
						<template #leading>
							<slot name="item-leading" />
						</template>
						<template #default>
							<slot name="item" />
						</template>
						<template #trailing>
							<slot name="item-trailing" />
						</template>
					</MenuItem>
				</slot>
			</div>
		</Frame>
	</span>
</template>
