<template>
	<!--
		Корень — `label`: клик по подписи выбирает радио, а подпись становится
		его доступным именем. На корне — `dataset` (`data-selected`,
		`data-disabled`), `attrs` (`dir`) и модификаторы размера, варианта и
		вида: тема читает всё отсюда.
	-->
	<label class="s-radio-group-item">
		<!--
			Нативное радио. Группировку по общему `name`, стрелки по кругу,
			пропуск выключенных, пробел, один Tab-стоп на группу и участие в
			форме даёт браузер. Набор `aria` элемента — сюда; `checked` и
			`disabled` нативные, ARIA-дублей им нет.

			Стоит перед контролом: кольцо фокуса тема рисует соседним
			селектором от него. Визуально радио скрыто темой.
		-->
		<input class="s-radio-group-item__input" type="radio" />
		<!--
			Кольцо и точка — декоративная разметка без текста: выбор
			скринридеру сообщает нативный `checked`. Точка стоит всегда — у
			невыбранного тема сжимает её в ноль, у вида `ring` прячет и
			утолщает кольцо.
		-->
		<span class="s-radio-group-item__control">
			<span class="s-radio-group-item__indicator"></span>
		</span>
		<!--
			Подпись: слот по умолчанию, запасное содержимое — `text` элемента.
			Подписи может не быть — тогда она лежит в соседнем элементе, а
			пустую обёртку тема прячет сама.
		-->
		<span class="s-radio-group-item__text">
			<slot />
		</span>
	</label>
</template>
