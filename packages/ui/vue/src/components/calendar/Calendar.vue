<template>
	<div class="s-calendar">
		<!--
			Calendar — сетки показанных месяцев и одна пара кнопок листания на
			все. Корень рисуется по `tag`. Роли у корня нет: сетку по APG (Date
			Picker Dialog) несёт каждая таблица.

			Разметка статическая: размер и вариант (`--size-*`, `--variant-*`),
			`data-disabled`, `dir`, наборы ARIA и обработчики приходят кодом,
			здесь только состав и имена классов. Нажатия и наведение на дни
			ловит плагин указателя, клавиши — плагин клавиатуры; обработчиков в
			разметке нет.

			Месяц, неделя, заполнитель и день здесь — по одному, как образец
			перебора: месяцы — `grids` коллекции, недели — `grid.weeks`, ячейки —
			неделя.
		-->

		<!--
			Кнопки листания — одна пара на весь календарь: «назад» и «вперёд»
			двигают все сетки разом. В DOM пара стоит ДО сеток, поэтому Tab
			проходит «назад», «вперёд» и остановку сетки — одну на все сетки. На
			экране кнопки разносит тема: «назад» у начала ряда заголовков,
			«вперёд» у конца, вровень с крайними колонками. Порядок DOM от этого
			не меняется.

			Вида разметка кнопкам не передаёт: красит их тема по контексту
			(`:where(.s-calendar__prev)`), как кнопки ленты Scroller. Значок —
			иконка роли `arrowRight` у обеих: своей роли «влево» в контракте
			иконок нет, стрелку «назад» зеркалит тема, в RTL — «вперёд».
		-->
		<Button class="s-calendar__prev">
			<slot name="prev-icon">
				<Icon />
			</slot>
		</Button>

		<!-- Кнопка «вперёд» — зеркальная пара «назад», см. комментарий выше. -->
		<Button class="s-calendar__next">
			<slot name="next-icon">
				<Icon />
			</slot>
		</Button>

		<!--
			Месяц — по одному на сетку (`grids`), ключ — `grid.key`. Месяцы стоят
			в ряд; высоту под шесть недель держит тема, и соседние сетки стоят
			вровень по строкам.
		-->
		<div class="s-calendar__month">
			<!--
				Заголовок месяца — текст `grid.title` и набор `grid.titleAria`
				(`id`, по которому сетку называет `aria-labelledby`). Не `h*`:
				уровень заголовка знает страница, а календарь стоит где угодно.
			-->
			<div class="s-calendar__title"></div>

			<!--
				Сетка — `table` с набором `grid.gridAria` (`role="grid"`, имя от
				заголовка, `aria-multiselectable`).
			-->
			<table class="s-calendar__grid">
				<!--
					Дни недели — короткие имена из `weekdays`, по `th` на день.

					Строку скрывает от скринридера код (`aria-hidden` на `thead`), и
					это отступление от APG, где у колонок есть заголовки: имя дня —
					полная дата, день недели в нём уже есть, и подписанная колонка
					прочла бы его второй раз.
				-->
				<thead>
					<tr class="s-calendar__weekdays">
						<th class="s-calendar__weekday"></th>
					</tr>
				</thead>

				<tbody>
					<!-- Неделя — семь ячеек, от первого дня недели. -->
					<tr class="s-calendar__week">
						<!--
							Заполнитель — день соседнего месяца, у ячейки нет элемента
							(`cell.item` пуст). Это не день: ни числа, ни состояний, ни
							фокуса — число повторило бы дату, которая стоит в соседней
							сетке. Пустая ячейка держит место в неделе и получает набор
							ячейки (`cell.aria` — скрыта от скринридера).
						-->
						<td class="s-calendar__filler"></td>

						<!--
							День — `Calendar.Item` над элементом коллекции `cell.item`,
							ключ — дата. Содержимое дня — слот `item` со scope `{ item }`
							(цена, точка события); без него день рисует свой номер.
						-->
						<CalendarItem>
							<slot name="item" />
						</CalendarItem>
					</tr>
				</tbody>
			</table>
		</div>
	</div>
</template>
