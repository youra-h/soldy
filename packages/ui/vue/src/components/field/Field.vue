<template>
	<div class="so-field">
		<!--
			Field — поле формы: подпись, контрол, подсказка и ошибка, связанные с
			контролом сами. На корне — модификаторы `so-field--position-*` (`top`,
			`start`, `end`) и `so-field--size-*`. Своих состояний у Field нет:
			выключенность, только чтение и обязательность тема читает с корня
			контрола, ошибку контрол рисует по своему `data-invalid`.

			Порядок частей один на все стороны — подпись, контрол, подсказка,
			ошибка: сторону рисует тема, по нему же сетка ставит подпись сбоку.
			Часть без текста не рисуется. Ошибка рисуется при `invalid` и встаёт
			на место подсказки: при ошибке подсказки нет.

			Комментарий — внутри корня, а не над ним: в разработке Vue оставляет
			комментарии, и корнем стал бы фрагмент.
		-->
		<!--
			Подпись — имя поля. Текст — проп `label`, своя разметка — слот
			`label-content`. Только сама подпись: её текст — доступное имя
			контрола, и описание сюда не кладут. С контролом её связывает код:
			`for` на поле у контролов с `<input>` (клик доходит до поля), `id` и
			`aria-labelledby` у групп — DateInput, DatePicker, RadioGroup.
		-->
		<label class="so-field__label"><slot name="label-content" /></label>
		<!-- Контрол — слот `default`: Input, Select, CheckBox, Label с контролом… -->
		<div class="so-field__control"><slot /></div>
		<!--
			Подсказка — проп `helper`, своя разметка — слот `helper-content`: в
			ней бывают ссылки и списки, отсюда `div`. Её `id` — в
			`aria-describedby` контрола.
		-->
		<div class="so-field__helper"><slot name="helper-content" /></div>
		<!--
			Ошибка — проп `error`, своя разметка — слот `error-content`; её `id` —
			в `aria-describedby` контрола вместо подсказки. Значок — роль `error`,
			декор: смысл несёт текст, а значок отличает ошибку от подсказки там,
			где цвета нет (режим принудительных цветов). Текст — в своей обёртке:
			ряд из значка и текста — флекс, и текст со ссылкой без обёртки
			разошёлся бы на отдельные коробки.
		-->
		<div class="so-field__error">
			<Icon class="so-field__error-icon" />
			<div class="so-field__error-text"><slot name="error-content" /></div>
		</div>
	</div>
</template>
