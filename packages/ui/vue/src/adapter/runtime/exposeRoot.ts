import type { Ref, SetupContext } from 'vue'

/**
 * `$el` экземпляра — корень компонента, когда корень шаблона не он.
 *
 * Путь потребителя к корню во Vue — `$el` экземпляра из `ref`, и даёт его сам
 * Vue: первый узел шаблона. У Frame, Dialog и Drawer первый узел шаблона —
 * `<teleport>`, и `$el` — его якорь в разметке родителя, узел-комментарий, а
 * панель телепортирована в другое место. Переопределить `$el` можно только
 * через `expose`: прокси экземпляра читает открытый ключ раньше свойств Vue.
 * Больше экземпляр ничего не открывает (`useExpose`).
 *
 * Узел — из ссылки адаптера на корень, той, что привязана к `TElementPlugin`.
 * Читается он через ссылку: сменился `tag` — `$el` отдаёт новый узел, корень
 * не отрисован — `null`.
 *
 * Отдельная функция, а не флаг `useAdapter`: `expose()` зовётся один раз на
 * `setup()`, а `useAdapter` у элемента коллекции зовётся дважды. Корень, который
 * Vue и так отдаёт верно, через неё не открывают: у Table `$el` — окно, внешний
 * узел, а к `TElementPlugin` привязана `table` внутри него.
 */
export function exposeRoot(
	expose: SetupContext['expose'],
	rootElement: Ref<Element | null> | undefined,
): void {
	expose({ $el: rootElement ?? null })
}
