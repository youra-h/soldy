/**
 * Текст поля на узле — свойством, и только когда он разошёлся с узлом, как
 * `:value` у Vue, поле адаптера React и `fieldText` у Svelte.
 *
 * Привязку `value={…}` Solid пишет в узел на каждую смену значения, с узлом не
 * сверяя (`node.value = …`), — и в разметке, и в спреде. Набранный текст плагин
 * ввода несёт в ядро, ядро — в разметку, и Solid записал бы узлу его же текст
 * на каждое нажатие. Каретку такая запись не двигает: HTML уводит её в конец,
 * только когда текст другой. Но запись из кода снимает с поля пометку
 * «изменено пользователем», и браузер перестаёт проверять `minlength` и
 * `maxlength`: поле короче `minlength` уходит с формой как верное.
 *
 * Поэтому `value` в атрибуты поля не идёт, а текст ставит свой `ref` поля: он
 * заводит эффект, который перечитывает значение при каждой его смене, а пишет
 * в узел, только когда оно разошлось с узлом. Набор узлу его же текст не
 * вернёт, значение из кода дойдёт и после набора, а смена другого атрибута
 * узел не трогает вовсе. `undefined` — пустое поле, как у Vue.
 *
 * Пишет он после атрибутов узла, как Vue, который ставит `value` последним.
 * `ref` Solid зовёт раньше, чем раскладывает атрибуты, а значение поля
 * зависит от них: `range` (ручка ширины колонки таблицы) прижимает его к
 * своему ходу, и до `min` и `max` ширина 150 стала бы 100 — ходом по
 * умолчанию. Поэтому эффект — пользовательский (`createEffect`), а не
 * отрисовки: эффект отрисовки выполнился бы тут же, внутри `ref`, а
 * пользовательский Solid выполняет после отрисовки, когда атрибуты на узле.
 * Текст на узле всё равно к возврату из `render`, как и остальные атрибуты:
 * пользовательские эффекты отрисовка выполняет до своего конца. Сторожит
 * «полоса с полем» в `__tests__/table.spec.tsx`: ширина 150 при ходе 100–300.
 *
 * Атрибуты `fieldText` ложатся на `<input>` последними, после атрибутов
 * потребителя. `ref` потребителя среди тех нет: он ведёт к корню поля, а не к
 * `<input>`, и отдаёт его `ref` корня (`useAdapter`, `toControlAttrs`).
 *
 * На сервере `ref` не зовётся, эффектов нет, и текст уходит атрибутом
 * `value`: его берёт геттер на отрисовке. Сервер от браузера отличает
 * `isServer` из `solid-js/web`, как `Teleport`. При гидратации узел уже держит
 * текст сервера, и эффект его не переписывает.
 *
 * Отметку и «выбрано частично» флажка Solid пишет свойствами узла и так: их
 * запись, совпавшая с узлом, ничего у поля не снимает.
 */

import { createEffect } from 'solid-js'
import { isServer } from 'solid-js/web'

/**
 * Атрибуты `<input>` для текста поля — спредом на поле, последними: в браузере
 * `ref` поля, на сервере — `value`.
 */
export type TFieldText =
	{ readonly ref: (node: HTMLInputElement) => void } | { readonly value: string | undefined }

/** Текст поля по геттеру `getText` — один раз на компонент. */
export function fieldText(getText: () => string | undefined): TFieldText {
	if (isServer) {
		return {
			get value() {
				return getText()
			},
		}
	}

	return {
		ref(node: HTMLInputElement) {
			// После атрибутов узла: `ref` Solid зовёт раньше них
			createEffect(() => {
				const text = getText() ?? ''

				if (node.value !== text) node.value = text
			})
		},
	}
}
