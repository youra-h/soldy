/**
 * Окна гидратации — общее у мемо адаптера, которые их переживают: раскладки
 * корня и частей (`root.ts`) и структуры компонента — веток и петель
 * (`../runtime/flow.ts`, `../runtime/KeyedFor.tsx`).
 *
 * Окно гидратации — время, пока Solid сверяет разметку сервера с тем, что
 * собирает браузер: открыт контекст гидратации (`sharedConfig.context`). Окон у
 * страницы бывает несколько. Кроме основного — `hydrate()` страницы — это
 * граница `Suspense`, чьё содержимое сервер дослал потоком
 * (`renderToStream`): пока её данные не пришли, браузер оставляет разметку
 * границы как есть, а когда пришли — гидратирует её, вернув на это время
 * контекст гидратации; и остров со своим `hydrate()`.
 *
 * Пока окно открыто, Solid считает узлы документа совпавшими с сервером — все,
 * а не только узлы своего окна:
 * - в узлы не пишет — ни атрибутов, ни класса, ни свойств, ни текста
 *   (`isHydrating` в `solid-js/web` смотрит на `isConnected` узла, а не на
 *   то, откуда он), а спред запоминает пропущенное как записанное;
 * - не снимает узлы у подключённого родителя и не вставляет новые в массив
 *   (`insertExpression`);
 * - новый элемент ищет по ключу гидратации текущего окна (`getNextElement`), а
 *   ключи сервер выдал там, где элементы стояли у него: под этим ключом чужой
 *   узел — его элемент и заберёт, — или никакого. Тогда в сборке разработки
 *   летит `Hydration Mismatch` и гидратация срывается (`sharedConfig.done`), а
 *   в сборке без `development` элемент создаётся молча, мимо разметки, и
 *   только `Dynamic` падает — `template is not a function`.
 *
 * Вход элемента меняет то, что браузер уже собрал: в основном окне — узлы выше
 * него, в позднем — и узлы вне границы, гидратированные раньше. Смену в окне
 * мемо адаптера держат до конца окна, а после отдают живое, и Solid пишет её
 * уже вне гидратации — второй проход после монтирования, обычный приём Solid
 * для расхождения сервера и браузера:
 * - первое значение мемо — живое, посчитанное при сборке. Собранное в окне,
 *   мемо считает его в той же точке, что сервер, и оно совпадает с разметкой
 *   сервера;
 * - пересчёт в любом окне — и в том, где мемо собрано, и в чужом — отдаёт
 *   прежнее. Источники он читает и тогда: сменились они уже после окна —
 *   мемо пересчитается живым сразу, даже если эффект ниже ещё не выполнен (его
 *   откладывают ждущий `lazy` и `Suspense` в заглушке);
 * - конец окна мемо узнаёт эффектом, который заводит себе в таком пересчёте
 *   (`awaitHydrationEnd`): пользовательские эффекты Solid выполняет, уже сняв
 *   контекст гидратации, — у основного окна ещё внутри `hydrate()`, у позднего
 *   — ещё в обработчике, который открыл его, когда пришли данные границы.
 *   Эффект объявляет конец окна сигналом, и мемо отдаёт живое;
 * - не пересчитанное за окно сигнала не читает и эффекта не заводит: его
 *   значение и так живое.
 *
 * На сервере окон нет: контекст там тоже есть, но он для ключей гидратации, а
 * не для неё самой.
 */

import { createEffect, createSignal, sharedConfig } from 'solid-js'
import { isServer } from 'solid-js/web'

/**
 * Открыто ли окно гидратации — условие `isHydrating` из `solid-js/web` без
 * узла: сам `isHydrating` Solid не экспортирует. Контекст гидратации Solid
 * снимает перед пользовательскими эффектами, а `done` ставит, когда
 * гидратацию сорвало расхождение с разметкой или первое делегированное
 * событие: в обоих случаях в узлы он пишет снова.
 */
export function hydrating(): boolean {
	return !isServer && Boolean(sharedConfig.context) && !sharedConfig.done
}

/**
 * Начальное значение мемо, которое переживает окна, — «ещё не считали».
 * Значение мемо может быть и пустым — набора части нет (`undefined`), условие
 * ветки ложно, — и только своя метка отличает первое значение от пустого.
 */
export const UNCOMPUTED = Symbol('uncomputed')

/**
 * Конец окна гидратации — сигнал без значения: его читает мемо, которое держит
 * за окно прежнее, а объявляет эффект, заведённый в том же пересчёте мемо.
 * Сигнал один на все мемо, как и состояние гидратации у Solid одно на документ
 * (`sharedConfig`): кончилось окно — живое отдают разом все мемо, что держали
 * прежнее.
 */
const [hydrationEnd, endHydration] = createSignal<void>(undefined, { equals: false })

/** Эффект мемо, которое держит прежнее, — объявляет конец окна гидратации. */
function announceHydrationEnd(): void {
	endHydration()
}

/**
 * Мемо пересчитано в окне гидратации и отдаёт прежнее: ждать конца окна —
 * читать его сигнал и завести эффект, который конец объявит (шапка файла).
 * Зовётся из пересчёта мемо — эффект тогда принадлежит мемо и уходит с его
 * следующим пересчётом, — после чтения источников.
 */
export function awaitHydrationEnd(): void {
	hydrationEnd()
	createEffect(announceHydrationEnd)
}
