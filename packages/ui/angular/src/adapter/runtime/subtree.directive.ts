import { Directive, signal, type Signal } from '@angular/core'

/** Поддерево есть: признак, пока база его не назвала, и у компонента без предка. */
export const SUBTREE_PRESENT: Signal<boolean> = signal(true).asReadonly()

/**
 * SubtreeDirective — носитель признака «поддерево компонента есть» для
 * поддерева по DI.
 *
 * У Vue корень с `v-if` снимает всё поддерево — и панели вложенных слоёв,
 * увезённые в `body`. Корень Angular не снимается, а прячется, и
 * `display: none` до увезённых панелей не доходит. Поэтому то, что у Vue
 * снимает поддерево, база компонента (`TComponentBase`) отдаёт поддереву этим
 * признаком, а слой (`TRootSpec.teleport`) прячется, когда его нет у предка.
 * Дерево DI — дерево объявлений, то есть поддерево Vue: проекция, шаблон,
 * вывод слотов.
 *
 * Носитель — директива без селектора, входов и выходов в `hostDirectives`
 * декоратора базы: её наследник получает, а `providers` — нет (у
 * `ɵɵProvidersFeature` нет `ngInherit`). Angular создаёт её раньше компонента,
 * и база в своём конструкторе берёт свою (`self`) и предка (`skipSelf`). Свой
 * признак база называет сразу, в конструкторе (`provide`): поддерево —
 * проекцию и шаблон компонента — Angular создаёт позже, и до него признак
 * никто не читает.
 *
 * Потребитель носитель не пишет и не читает, но компилятор библиотеки
 * требует, чтобы host-директива класса из экспорта была видна из точки входа
 * пакета (NG3001). Поэтому бочка адаптера отдаёт его только под закрытым
 * именем `ɵSubtreeDirective`, как закрытое API Angular.
 */
@Directive({ standalone: true })
export class SubtreeDirective {
	private _present: Signal<boolean> = SUBTREE_PRESENT

	/** Поддерево компонента есть — признак, который назвала база. */
	get present(): Signal<boolean> {
		return this._present
	}

	/** База называет признак своего поддерева — в конструкторе, раньше поддерева. */
	provide(present: Signal<boolean>): void {
		this._present = present
	}
}
