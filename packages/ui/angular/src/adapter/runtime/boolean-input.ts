/**
 * booleanInput — transform булева входа: атрибут без значения включает проп.
 *
 * Атрибут без значения (`<soldy-button disabled>`) Angular отдаёт входу пустой
 * строкой — значением атрибута по HTML. Без transform пустая строка доходила
 * до ядра, и кнопка оставалась включённой. Vue, JSX-адаптеры и Web Components
 * такой атрибут включают по правилам HTML; transform делает то же самое.
 * Angular прогоняет через него любую запись входа — атрибут, привязку,
 * `setInput` — до `ngOnChanges` и до записи в поле, поэтому чтение входов в
 * `TComponentBase` о нём не знает.
 *
 * Тип записи строгая проверка шаблона берёт у параметра transform, а не у
 * поля входа: в декларации пакета это `ngAcceptInputType_<вход>`. Поэтому
 * параметр — ровно `boolean | '' | undefined`: `disabled` без значения
 * проходит, а `disabled="yes"` и `[disabled]="'yes'"` остаются ошибкой. Со
 * `string` прошла бы любая строка. `booleanAttribute` из `@angular/core` не
 * годится вдвойне: параметр у него `unknown`, и сверка пропала бы, а
 * `undefined` он превращает в `false` — снятый `visible` не вернулся бы к
 * умолчанию `true`. Здесь `undefined` проходит как есть: снятый вход связка
 * возвращает к умолчанию декларации.
 *
 * Функция, без дженерика и перегрузок, с явным типом параметра — иначе
 * компилятор Angular transform отклонит. В бочки не входит: сгенерированные
 * метаданные импортируют модуль сами, а в декларации пакета уходит только
 * тип параметра.
 */
export function booleanInput(value: boolean | '' | undefined): boolean | undefined {
	return value === '' ? true : value
}
