/**
 * Id монтирования Angular — счётчик приложения.
 *
 * Id места в дереве, общего у сервера и браузера, Angular не даёт: `useId`
 * у него нет. Зато полная гидратация создаёт компоненты в том же порядке, что
 * и серверный рендер той же страницы, — по шаблонам, сверху вниз. Поэтому id
 * монтирования — номер сборки компонента в своём приложении: сервер и
 * браузер, собирая ту же страницу, выдают компонентам те же номера.
 *
 * Счётчик — у приложения (корневой инжектор, `providedIn: 'root'`), а не у
 * процесса и не у набора плагинов: сервер рисует каждый запрос своим
 * приложением, и номера каждого запроса начинаются заново, а общий счётчик
 * процесса разошёлся бы с браузером, как своё `so-<n>` набора. Префикс — `APP_ID`
 * приложения: у двух приложений на одной странице `APP_ID` разные (этого
 * Angular требует сам), и номера их компонентов не сталкиваются.
 *
 * Токен наружу не выходит: номер берёт только сборка компонента
 * (`createAngularAdapterContext`).
 */

import { APP_ID, InjectionToken, inject } from '@angular/core'

/** Выдаёт следующий id монтирования приложения: `<APP_ID>-<номер>`. */
type TNextMountId = () => string

const MOUNT_ID = new InjectionToken<TNextMountId>('soldy:mount-id', {
	providedIn: 'root',
	factory: () => {
		const prefix = inject(APP_ID)
		let count = 0

		return () => `${prefix}-${++count}`
	},
})

/**
 * Следующий id монтирования приложения. Зовётся в контексте инъекции
 * компонента — его даёт сборке база (`TComponentBase`,
 * `runInInjectionContext`): DI Angular разрешает `inject` только там.
 */
export function nextMountId(): string {
	return inject(MOUNT_ID)()
}
