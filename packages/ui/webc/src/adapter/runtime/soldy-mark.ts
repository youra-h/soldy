/**
 * Метка элемента soldy — элемента, которого собирает база (`SoldyElement`):
 * ставит её база каждому своему элементу при создании.
 *
 * Читает её телепорт (`teleport.ts`): хозяин места панели — ближайший элемент
 * soldy вверх от её якоря. Колбэки хозяина приходят синхронно, и панель идёт за
 * местом вместе с ним — пересобирается после его сборки и уходит с ним со
 * страницы. Провайдер локали и элементы приложения хозяевами не бывают: их
 * место сторожит наблюдатель документа. Ещё по метке настоящее отключение
 * корня слоя находит элементы soldy в нём — им оно записывает долг
 * (`relocation.ts`).
 *
 * Метка — по самому элементу, а не атрибутом и не классом элемента: атрибут
 * оставил бы след в DOM, а класс элемента у каждого компонента свой, и у
 * наследника компонента (`class extends TButtonElement`) — тоже свой.
 *
 * В бочку адаптера не входит: это механика базы.
 */

/** Элементы, которых собирает база. */
const marked = new WeakSet<Node>()

/** Элемент собирает база — его конструктор, при создании (см. шапку). */
export function markSoldyElement(element: Element): void {
	marked.add(element)
}

/** Собирает ли узел база: элемент soldy — хозяин места для панелей, чей якорь в нём. */
export function isSoldyElement(node: Node): boolean {
	return marked.has(node)
}
