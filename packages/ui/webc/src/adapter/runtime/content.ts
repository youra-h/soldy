/**
 * Содержимое ли узел света: элемент или текст не из одних пробелов. Пробелы
 * между тегами — след переносов строк в разметке, а комментарий не рисуется.
 * Якорь увезённого корня — содержимое: он стоит на месте корня
 * (`TTeleport.rootAt`).
 *
 * Правило одно на базу и шаблон: слот без содержимого не задан
 * (`SoldyElement`), и копию образца без содержимого шаблон не отдаёт в образец
 * элемента из данных (`lendTemplates`) — иначе пустой образец заглушил бы то,
 * что элемент рисует сам.
 *
 * В бочку адаптера не входит: это механика базы и шаблона.
 */

import { TTeleport } from './teleport'

export function isContent(node: Node): boolean {
	if (node instanceof Element || TTeleport.rootAt(node)) return true

	return node instanceof Text && node.data.trim() !== ''
}
