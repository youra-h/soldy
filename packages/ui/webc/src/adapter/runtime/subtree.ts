/**
 * Поддерево элемента soldy — признак «оно есть» в контексте места.
 *
 * У Vue корень с `v-if` снимает всё поддерево — и панели вложенных слоёв,
 * увезённые в `body`: подменю, поповер в панели поповера, окно в панели.
 * Элемент soldy не снимается, а прячется (`SoldyElement`), и `display: none`
 * до увезённых панелей не доходит: они стоят в цели, а не под ним. Поэтому то,
 * что у Vue снимает поддерево, база элемента отдаёт своему месту признаком, а
 * слой — корень с телепортом (`TRootSpec.teleport`) — прячется, когда признака
 * нет у предка. Узел у плагинов без него снимает любой элемент поддерева, не
 * только слой: `TElementPlugin` получает `null`, как от `v-if` у Vue. Что
 * снимает поддерево, решает база (`SoldyElement`, шапка, «Поддерево»); здесь —
 * только носитель.
 *
 * Носитель — источник (`TSubtree`): значение и подписка. Свой источник у
 * элемента один на всё время жизни, и элемент отдаёт его месту при создании —
 * раньше, чем соберётся кто-то под ним. Ближайший источник выше по месту
 * элемент берёт на каждую сборку и подписывается на него: место — у сборки, и
 * элемент, переставленный под другого предка, берёт уже его. Увезённый корень
 * ищет предка от якоря (`TPlaceContext.above`) — тем же путём, что телепорт ищет
 * хозяина места, — поэтому панель подменю видит подменю, оно — панель меню, та
 * — меню.
 *
 * Смена значения доходит до подписчиков сразу, тем же вызовом: подписчик
 * пересчитывает своё скрытие, узел плагинам и свой признак, и вся цепочка
 * вложенных слоёв прячется за одну отрисовку предка.
 *
 * В бочку адаптера не входит: это механика базы.
 */

import { TPlaceContext } from '../context'

/** Источник признака «поддерево есть» — свой у каждого элемента soldy. */
export class TSubtree {
	/** Поддерево есть — пока база его не пересчитала, и у элемента без предка. */
	private _present = true

	/** Подписчики — элементы ниже по месту, на свою сборку. */
	private readonly _listeners = new Set<() => void>()

	/** Поддерево есть. */
	get present(): boolean {
		return this._present
	}

	/** Записать признак: то же значение — ничего, сменилось — подписчики узнают сразу. */
	set present(value: boolean) {
		if (value === this._present) return

		this._present = value

		// Копия: подписчик, которого смена сняла, остальных не сбивает
		for (const listener of [...this._listeners]) listener()
	}

	/** Подписка на смену признака; отдаёт отписку. */
	subscribe(listener: () => void): () => void {
		this._listeners.add(listener)

		return () => {
			this._listeners.delete(listener)
		}
	}
}

const SUBTREE = new TPlaceContext<TSubtree>()

/** Отдать признак элемента всему, что стоит ниже него по месту. */
export function provideSubtree(element: Element, subtree: TSubtree): void {
	SUBTREE.provide(element, subtree)
}

/**
 * Признак ближайшего элемента soldy выше узла по месту; такого нет —
 * `undefined`, и поддерево есть. Зовётся при сборке, когда элемент подключён.
 */
export function nearestSubtree(node: Node): TSubtree | undefined {
	return SUBTREE.nearest(node)
}
