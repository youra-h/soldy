/**
 * Метка слота — комментарий, который шаблон владельца кладёт в слот своей
 * детали (`lendMark`, `template/mark.ts`): слот с меткой задан, даже когда
 * больше в нём ничего нет, а узлы владелец ставит перед ней (`lendBefore`).
 *
 * Обёртку слота деталь строит, только когда в слот есть что положить
 * (`leading` у Input), и узнаёт об этом при построении: слот без содержимого
 * не задан (`isContent`). Но владелец бывает обязан отдать слот и пустым: Select
 * отдаёт полю `leading` всегда, как Vue свой шаблон `#leading`, — там теги в
 * `multiple`, — и обёртка `.so-input__leading` стоит и в `single`: тема
 * держит по ней отступ поля и место под теги. Содержимого к построению детали
 * в слоте может не быть, и теги владелец ставит туда позже, на смену режима.
 * Поэтому слот задаёт метка: база при построении считает слот с ней заданным
 * (`SoldyElement`), и метка встаёт в его точку вместе с остальным светом, а
 * узлы владельца встают перед ней — до сборки детали в её свет, после — в её
 * слот. Метка остаётся там, куда деталь положила слот, и узел перед ней встаёт
 * на своё место в любой момент: так и значок кнопки разворота окна сменяется
 * по `maximized` без обёртки, которой нет у Vue.
 *
 * Метка — по самому узлу, а не атрибутом: комментарий атрибутов не несёт, а
 * пустой комментарий в свете — не содержимое. Слот метки помнит реестр:
 * назначение (`assignment.ts`) раскладка света детали забирает, а узлу перед
 * меткой слот нужен и позже.
 *
 * В бочку адаптера не входит: это механика базы и шаблона.
 */

/** Метки слотов: узел → слот детали, который он задаёт. */
const marks = new WeakMap<Node, string>()

/** Узел — метка слота `slot` своей детали (см. шапку). */
export function markSlot(mark: Comment, slot: string): void {
	marks.set(mark, slot)
}

/** Метка ли узел: слот, в котором она стоит, задан и пустым. */
export function isSlotMark(node: Node): boolean {
	return marks.has(node)
}

/** Слот детали, который задаёт метка; узел не метка — `undefined`. */
export function slotOfMark(node: Node): string | undefined {
	return marks.get(node)
}
