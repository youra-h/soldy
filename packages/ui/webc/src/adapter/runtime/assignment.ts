/**
 * Назначенный слот — место узла в свете элемента, которое назначил шаблон
 * владельца, а не атрибут `slot`.
 *
 * Свет элемента база раскладывает по атрибуту `slot` (`ElementBase`). Но у
 * детали шаблона — строки таба, заголовка секции — свет приходит не из
 * разметки потребителя, а от владельца: его слот ведёт в слот детали
 * (`TSlotTarget.slot`), и узел встаёт в деталь, пока та ждёт своей сборки.
 * Атрибут `slot` на узле — имя слота владельца (`header` секции), а детали он
 * нужен под своим именем (`default` заголовка), и у текста атрибутов нет вовсе.
 * Поэтому место назначается узлу здесь, а раскладка света детали берёт его
 * раньше атрибута. Так же встают в элемент из данных копии образцов `item-*`
 * владельца — вместе с текстом.
 *
 * Назначение действует до раскладки света: детали оно больше не нужно, и узел,
 * переставленный потом в чужой свет, раскладывается по своему атрибуту.
 *
 * В бочку адаптера не входит: это механика базы, назначает шаблон помощником
 * `lend` (`template/lend.ts`).
 */

/** Узел → слот, который ему назначил шаблон владельца. */
const assigned = new WeakMap<Node, string>()

/** Назначить узлу слот в свете элемента, куда его ставит шаблон. */
export function assignSlot(node: Node, slot: string): void {
	assigned.set(node, slot)
}

/**
 * Слот, назначенный узлу, — один раз: раскладка света забирает назначение,
 * и дальше узел живёт по своему атрибуту. Не назначен — `undefined`.
 */
export function takeAssignedSlot(node: Node): string | undefined {
	const slot = assigned.get(node)

	if (slot !== undefined) assigned.delete(node)

	return slot
}
