/**
 * Разметка владельца — элементы soldy, которые построил шаблон библиотеки, а не
 * написал потребитель: детали (`createDetail` — кнопка очистки поля, строка
 * таба, стрелки пагинации) и элементы из данных (`createItem` — элементы
 * `items` и `engine` коллекций, страницы Pagination).
 *
 * Событие элемента soldy всплывает, только если элемент написал потребитель —
 * разметкой или кодом. Событие элемента разметки владельца слышно только на
 * нём самом (`useAdapter.ts`), как в остальных адаптерах, где событие
 * вложенного компонента слышит только разметка, в которой он стоит. Иначе
 * `so:action:press` кнопки очистки дошёл бы до слушателей поля и до
 * делегирования на форме как событие самого поля, а `so:element:ready` и
 * `so:change:text` каждой страницы — до слушателей пагинации. Что из этого
 * нужно приложению, сообщает сам владелец своим событием (`so:change:value`,
 * `so:item:activated`, `so:item:close`).
 *
 * Метка — по самому элементу, а не атрибутом и не `embedded`. `embedded` —
 * признак для реестра плагинов, и у элемента из данных его нет: плагин
 * приложения со `scope: 'own'` на него ставится, а на деталь — нет. Атрибут
 * оставил бы след в DOM, и копия, которую снял код потребителя (`cloneNode`),
 * унесла бы его с собой, хотя это уже элемент потребителя. Ставит метку
 * помощник шаблона при создании элемента, до вставки, — раньше, чем элемент
 * собирается.
 *
 * В бочку адаптера не входит: это механика базы и шаблона.
 */

/** Элементы, которые построил шаблон библиотеки. */
const markup = new WeakSet<Element>()

/** Элемент построил шаблон библиотеки — помощник шаблона, до вставки (см. шапку). */
export function markOwnerMarkup(element: Element): void {
	markup.add(element)
}

/** Построил ли элемент шаблон библиотеки: тогда его события не всплывают. */
export function isOwnerMarkup(element: Element): boolean {
	return markup.has(element)
}
