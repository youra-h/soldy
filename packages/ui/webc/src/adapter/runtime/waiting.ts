/**
 * Ожидание — сборка, пришедшая, пока подключается другой элемент soldy, идёт
 * сразу после него, в порядке прихода.
 *
 * Колбэки DOM у элемента soldy приходят тем же вызовом DOM, что их вызвал
 * (`SoldyElement`), а подключение элемента само трогает DOM: раскладка света
 * переносит детей в точки шаблона, `create()` ставит в корень детали, первая
 * отрисовка — элементы из данных. Подключения этих детей приходят внутри
 * подключения их родителя, раньше, чем он собрался, — и собираться им рано:
 *
 * - элемент коллекции берёт движок владельца лифтом (`up()`), а владелец
 *   опускает его при своей сборке — после раскладки света. Элементы разметки,
 *   собранные внутри неё, не нашли бы владельца, и после `innerHTML` коллекция
 *   осталась бы пустой;
 * - деталь шаблона получает свет от владельца — узлы, которые он назначил её
 *   слотам (свет детали, `TSlotTarget.slot`). Собранная в `create()`, она
 *   разложила бы свет раньше, чем владелец его отдал.
 *
 * Поэтому подключение внутри подключения встаёт в очередь (`wait`), а очередь
 * идёт, когда кончилось внешнее (`connecting`): каждая сборка из неё — тоже
 * подключение, и пришедшие во время неё встают в конец. Порядок прихода — это
 * порядок документа: раскладка света переносит детей по порядку, и элементы
 * разметки входят в коллекцию в порядке DOM.
 *
 * Элемент сам решает, что делать в свою очередь (`_resume`): к этому времени
 * его могли снять, и тогда он не собирается. С полифилом (Safari) колбэки
 * приходят его наблюдателем, микрозадачей позже, — уже вне подключения
 * родителя, и ждать им нечего.
 *
 * В бочку адаптера не входит: это механика базы.
 */

/** Сколько подключений идёт сейчас: подключение, начатое внутри другого, — вложенное. */
let depth = 0

/** Сборки, которые ждут конца идущего подключения, — в порядке прихода. */
const waiting: (() => void)[] = []

/** Идёт ли сейчас подключение элемента soldy. */
export function isConnecting(): boolean {
	return depth > 0
}

/**
 * Подключение элемента: сборки, пришедшие во время него, ждут его конца, а
 * когда кончилось внешнее подключение — идут по порядку.
 */
export function connecting(run: () => void): void {
	depth += 1

	try {
		run()
	} finally {
		depth -= 1

		if (depth === 0) drain()
	}
}

/** Сборка ждёт конца идущего подключения: `resume` позовут в её очередь. */
export function wait(resume: () => void): void {
	waiting.push(resume)
}

/**
 * Очередь — до конца: сборка, упавшая с ошибкой, остальных не держит, а
 * первая ошибка уходит дальше, к колбэку, который очередь пустил.
 */
function drain(): void {
	let failed = false
	let failure: unknown

	for (let next = waiting.shift(); next; next = waiting.shift()) {
		try {
			next()
		} catch (error) {
			if (!failed) {
				failed = true
				failure = error
			}
		}
	}

	if (failed) throw failure
}
