/**
 * Контракт шаблона Web Components.
 *
 * Фреймворка нет, поэтому шаблон — это не разметка, а описание структуры плюс
 * привязки «проп → DOM-операция». Такое описание даёт то же, что даёт шаблон в
 * остальных адаптерах: вынесено в отдельный файл и не смешано с классом.
 *
 * Точечность обновлений берётся отсюда: подписка на связку (`subscribe`) уже сообщает,
 * КАКОЙ проп изменился, а привязка знает, за какие пропы она отвечает. Значит
 * при смене `text` не нужно трогать `className`.
 *
 * Корень — сам элемент (`<button is="so-button">`): шаблон строит структуру
 * прямо в нём. То, что ядро пишет на корень, — классы, наборы `aria`, `attrs`,
 * `dataset`, скрытие по `rendered` и `visible` — раскладывает база
 * (`SoldyElement`): это одинаково у всех визуальных компонентов soldy, и
 * шаблону остаётся только своё. Что элемент делает по тегу — кнопка с формой,
 * — делает браузер: элемент и есть нативный элемент своего тега. У элемента-
 * обёртки корень строит шаблон — `table` в окне таблицы, регион тостов
 * (`TTemplateParts.root`), — и на него база кладёт то же; скрытие у окна
 * таблицы остаётся на элементе, а у корня, который уезжает в слой, — на нём
 * самом. Подложку окна, соседку корня в цели, шаблон отдаёт спутником
 * (`TTemplateParts.companion`): ставит, увозит и прячет её база.
 *
 * Набор ядра на элементе шаблона, а не на корне, — `aria` поля на `<input>`,
 * `clearAria` поля на кнопке очистки — кладёт шаблон функцией
 * `ownerAttributes` (`attributes.ts`): верхним слоем раскладчика элемента, тем
 * же правилом, что база на корне. Тем же вызовом — набор для содержимого слота,
 * которому остальные адаптеры отдают его в scope: связку с панелью триггеру
 * Popover и Tooltip (`triggerAria`). Scope у слотов Web Components нет, и
 * привязать набор потребитель не может, поэтому шаблон кладёт его на первый
 * элемент слота — узлы слота отдаёт контекст (`slotted`). Состояние в
 * контексте — свойства инстанса и выходы плагинов его дескриптора: пометку
 * панели владельцем (`dismiss_ownerAttribute`) шаблон читает с типом. Стиль
 * значением на узле шаблона — позицию ручки Slider, долю заливки звезды
 * Rating, высоту распорки окна — тем же правилом кладёт `ownerStyles`
 * (`styles.ts`). Вложенный элемент soldy —
 * деталь разметки владельца — шаблон строит помощником `createDetail` с
 * обязательным именем места (`embedded`), а свою разметку отдаёт в её слот
 * помощником `lend`.
 * Элементы коллекции из данных шаблон владельца рисует петлёй по ключу
 * (`TKeyedLoop`, `loop.ts`).
 */

import type { TBindingState } from '../runtime/useAdapter'

/**
 * Куда попадает содержимое слота.
 *
 * Режимы `append` и `before` — потому, что слоты соседствуют в одном родителе:
 * `default` у Button лежит ВНУТРИ `.so-button__text`, а `leading` — ПЕРЕД этим
 * узлом. Режим `before` позволяет обойтись без узлов-обёрток, которых нет в
 * остальных пяти адаптерах: лишний `<span>` вокруг иконки сломал бы селекторы
 * темы.
 *
 * - `append` со слотом детали (`slot`) — точка ведёт в слот детали шаблона:
 *   узлы встают в деталь (строку таба, заголовок секции) и назначаются её
 *   слоту (`slot`), а не по своему атрибуту `slot`. Деталь ждёт своей сборки,
 *   пока подключается владелец, и раскладывает их уже по назначению: `header`
 *   секции становится `default` заголовка, `close-icon` таба — содержимым
 *   кнопки закрытия;
 * - `before` со слотом детали — точка — узел шаблона в свете детали (метка):
 *   узлы встают перед ним и назначаются слоту детали, а деталь, собравшись,
 *   кладёт их в свой слот вместе с меткой. Метка остаётся там, где деталь
 *   положила слот, поэтому слот, который выводит привязка (`showSlot`),
 *   возвращается на своё место в детали и после её сборки: так значок кнопки
 *   разворота окна меняется по состоянию без обёртки, которой нет в разметке
 *   остальных адаптеров;
 * - `sample` — точка-образец: содержимое база не выводит, а держит у себя —
 *   слот задан (`hasSlot`), а копию отдаёт контекст (`sample`). Так владелец
 *   коллекции берёт слоты `item-*`: копию образца он кладёт в каждый свой
 *   элемент из данных, в его слот.
 */
export type TSlotTarget =
	| {
			mode: 'append'
			node: HTMLElement
			/** Слот детали, в которую ведёт точка: узлы назначаются ему (см. выше). */
			slot?: string
	  }
	| {
			mode: 'before'
			node: Node
			/** Слот детали, в свете которой стоит узел-метка: узлы назначаются ему (см. выше). */
			slot?: string
	  }
	| { mode: 'sample' }

/**
 * Точки распределения света: имя слота → куда класть содержимое. Порядок
 * ключей значим: свет раскладывается по слотам в порядке объявления, и в
 * одну точку `append` содержимое слота, объявленного раньше, встаёт раньше —
 * при любом порядке в разметке.
 */
export type TSlotTargets = Record<string, TSlotTarget>

/** Задан ли слот: в свете элемента есть его содержимое. */
export type TSlotGiven = (name: string) => boolean

/** Что построил шаблон в корне: точки слотов, узел поля, корень в обёртке и спутник корня. */
export type TTemplateParts = {
	/** Точки распределения света — см. `TSlotTargets`. */
	readonly slots: TSlotTargets
	/**
	 * Узел поля — вложенный `<input>` Input, CheckBox, Switch и радио, строка
	 * таба, секции и элемента списка, узел списка с ролью у ListBox и Tabs,
	 * `table` в окне таблицы. Есть только у корня с полем (`TRootSpec.control`):
	 * на него база при построении переносит статические атрибуты разметки
	 * элемента.
	 */
	readonly control?: HTMLElement
	/**
	 * Корень компонента внутри элемента — `table` в окне таблицы, регион тостов
	 * в `<so-toasts>`. Есть только у элемента-обёртки (`TRootSpec.wrapped`): на
	 * этот узел база кладёт классы, наборы и стиль ядра, с ним связывает
	 * `TElementPlugin` и его тег отдаёт ядру. Окну таблицы база оставляет
	 * скрытие и класс и стиль потребителя, а корень, который уезжает в слой
	 * (регион тостов), получает и их: элемент вокруг него — только место.
	 */
	readonly root?: HTMLElement
	/**
	 * Спутник корня слоя — узел шаблона рядом с корнем, а не в нём: подложка
	 * окна и выезжающей панели, сосед панели, как в телепорте Vue. Есть только у
	 * корня, который уезжает в слой (`TRootSpec.teleport`): база ставит его
	 * прямо перед корнем, увозит в цель и возвращает на место той же операцией,
	 * что корень, уводит за местом вместе с ним и прячет вместе с ним — по
	 * `rendered`, `visible` и без цели. Настоящее отключение элемента его
	 * снимает, подключение возвращает к корню. Свои наборы и стиль на нём кладёт
	 * шаблон.
	 */
	readonly companion?: HTMLElement
}

/**
 * Контекст привязок и построения: живой вид элемента. `TOutputs` — выходы
 * плагинов дескриптора компонента (`DescriptorPluginOutputs`), их шаблон
 * читает в состоянии рядом со свойствами инстанса.
 */
export interface ITemplateContext<TInstance = object, TFacade = unknown, TOutputs = unknown> {
	/**
	 * Сам элемент — корень компонента, а у элемента-обёртки
	 * (`TRootSpec.wrapped`) — узел вокруг корня, который построил шаблон
	 * (`TTemplateParts.root`): окно таблицы, место региона тостов. Части
	 * элемента шаблон помнит по нему.
	 */
	readonly root: HTMLElement
	/** Узел слота по умолчанию — там же, куда перенесён свет без атрибута slot */
	readonly content: HTMLElement
	/**
	 * Свойства инстанса компонента со снимком через `valueOf()` — текущей
	 * связки, с выходами плагинов его дескриптора (`dismiss_ownerAttribute`); у
	 * коллекционного компонента — вместе со свойствами фасада (`items`,
	 * `shown`, `active`, `order`): имена пропсов фасада и выходов плагинов
	 * префиксуются, и одноимённых у них нет. Вид — тот же, что у связки
	 * (`TBindingState`): выходы — одним видом с инстансом.
	 */
	readonly state: TBindingState<TInstance, TFacade, TOutputs>
	/**
	 * Инстанс компонента — текущей связки: его команды зовёт разметка (`clear`
	 * кнопки очистки поля). Читается в момент обращения, поэтому обработчик,
	 * который запомнил контекст, зовёт инстанс той связки, что живёт сейчас, а
	 * не той, при которой он встал. До первой сборки инстанса нет.
	 */
	readonly ctrl: TInstance | undefined
	/**
	 * Фасад коллекции текущей связки — у компонента с двумя контекстами (свой и
	 * фасада): через его контекст элемента разметка зовёт команды коллекции —
	 * активировать таб, раскрыть секцию, закрыть таб. Читается в момент
	 * обращения, как `ctrl`: каждое подключение — новая связка и новый фасад. У
	 * остальных компонентов и до первой сборки его нет.
	 */
	readonly facade: TFacade | undefined
	/** Задано ли пользователем содержимое именованного слота — и точки-образца */
	hasSlot(name: string): boolean
	/**
	 * Узлы заданного слота — его свет в точке слота, в порядке разметки. Так
	 * шаблон кладёт набор на содержимое потребителя, которому остальные
	 * адаптеры отдают его в scope: связку с панелью — первому элементу слота
	 * `trigger` у Popover и Tooltip (`ownerAttributes`). Узлы — те самые, что
	 * написал потребитель, а не копии: триггер остаётся тем же узлом, и набор
	 * на нём сменяется на месте. Слот не задан, шаблон его не объявил или это
	 * образец (его копию отдаёт `sample`) — пусто.
	 */
	slotted(name: string): readonly ChildNode[]
	/**
	 * Копия образца — содержимого слота, который шаблон объявил образцом
	 * (`TSlotTarget` с `sample`): `<template slot="item-leading">` даёт копию
	 * своего содержимого, другой узел — копию себя, без атрибута `slot`. Каждый
	 * вызов — новая копия. Слот не задан или не образец — `null`.
	 */
	sample(name: string): DocumentFragment | null
	/**
	 * Показать или снять слот, который выводит привязка, а не раскладка света:
	 * содержимое ручки Switch по значению, отметку CheckBox по состоянию.
	 *
	 * Точку такого слота объявляет `create()`, и раскладка света кладёт туда
	 * содержимое, как у любого слота; дальше слот ведёт привязка. Снятое уходит
	 * из документа, и элементы soldy в нём отключаются, как при перестановке.
	 * Показ — переносом силами базы: собранное раньше не пересобирается. Слот
	 * не задан — делать нечего.
	 */
	showSlot(name: string, shown: boolean): void
}

/**
 * Привязка «проп → DOM-операция».
 *
 * `apply` — метод: общая привязка, объявленная для части инстанса (`{ text }`),
 * подходит шаблону любого компонента, у которого эта часть есть.
 */
export interface ITemplateBinding<TInstance = object, TFacade = unknown, TOutputs = unknown> {
	/** Пропы, при изменении которых привязку надо применить */
	props: readonly string[]
	apply(ctx: ITemplateContext<TInstance, TFacade, TOutputs>): void
}

export interface ITemplate<TInstance = object, TFacade = unknown, TOutputs = unknown> {
	/**
	 * Строит структуру в корне — в самом элементе — и отдаёт точки
	 * распределения света и узел поля. Зовётся один раз, при первом
	 * подключении: перестановка элемента в DOM структуру не пересоздаёт. Какие
	 * слоты заданы, к этому времени уже известно (`hasSlot`): обёртку слота
	 * шаблон строит, только когда в неё есть что положить. Ключи точек обязаны
	 * совпадать с именами слотов из дескриптора — это проверяет
	 * conformance-тест.
	 *
	 * Контекст — тот же живой вид элемента, что у привязок: обработчик, который
	 * шаблон заводит на узле при построении (клик строки таба, `change` радио),
	 * зовёт команды той связки, что живёт в момент события (`ctx.facade`), а не
	 * той, при которой узел построен.
	 */
	create(
		root: HTMLElement,
		hasSlot: TSlotGiven,
		ctx: ITemplateContext<TInstance, TFacade, TOutputs>,
	): TTemplateParts

	bindings: readonly ITemplateBinding<TInstance, TFacade, TOutputs>[]
}

/** Объявление привязки: bind('text', ctx => ...) или bind(['a','b'], ...) */
export function bind<TInstance, TFacade = unknown, TOutputs = unknown>(
	props: string | readonly string[],
	apply: (ctx: ITemplateContext<TInstance, TFacade, TOutputs>) => void,
): ITemplateBinding<TInstance, TFacade, TOutputs> {
	return {
		props: typeof props === 'string' ? [props] : props,
		apply,
	}
}
