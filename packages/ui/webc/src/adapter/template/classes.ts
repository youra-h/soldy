/**
 * Классы значением на узле шаблона — функцией шаблона, по правилу базы.
 *
 * Свои классы база кладёт на корень (`ElementBase`). Классы части без своего
 * экземпляра — панели меню и подменю (`panelClasses`: блок `so-menu__panel` с
 * размером и вариантом), — кладёт сам шаблон: функцией `ownerClasses`, тем же
 * правилом, что база на корне (`applyClasses`, `root-attributes.ts`). Панель —
 * Frame, деталь шаблона: свои классы (`so-frame`) на неё кладёт его база, и
 * классы владельца стоят рядом с ними, как класс потребителя. Своё значение
 * функция пишет и снимает, а чужое не трогает: класс, который на узле уже был
 * до того, как его назвал набор, — потребителя или Frame. Память — у узла, как
 * у стиля (`ownerStyles`): каждый вызов кладёт классы новой записи поверх
 * прежних, и ушедший из записи класс снимается — смена размера меняет
 * модификатор.
 *
 * Классы — снимок ядра списком (`TClasses` → `string[]`), как их отдаёт
 * состояние; снимка нет — классов нет.
 */

import { applyClasses, type TAppliedClasses } from '../runtime/root-attributes'

/** Что из классов поставил шаблон на узел в прошлый раз. */
const applied = new WeakMap<Element, TAppliedClasses>()

/** Классы владельца на элементе его шаблона; классов нет — свои сняты. */
export function ownerClasses(element: Element, classes: readonly string[] | undefined): void {
	applied.set(element, applyClasses(element, classes ?? [], applied.get(element) ?? new Set()))
}
