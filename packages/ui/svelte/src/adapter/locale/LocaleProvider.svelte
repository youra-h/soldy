<script lang="ts">
	import { untrack } from 'svelte'
	import { TLocaleSource } from '@soldy-ui/plugins'
	import { provideLocale } from './context'
	import type { TLocaleProviderProps } from './types'

	const props: TLocaleProviderProps = $props()

	// Источник — с локалью первой отрисовки: имена нужны уже в ней, в том
	// числе на сервере, где эффекты не выполняются. `untrack` — только чтобы
	// чтение пропа было явно разовым: дальше смену пишет эффект
	const source = new TLocaleSource(untrack(() => props.locale))

	provideLocale(source)

	// Смена пропа — в тот же источник: плагины языка и имён переписывают
	// компонентам тег и имена, а компоненты не перемонтируются. Эффект `pre` —
	// до обновления DOM: имена меняются тем же проходом, что и разметка
	$effect.pre(() => {
		source.locale = props.locale
	})
</script>

