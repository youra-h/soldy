/**
 * «Сегодня» гидратации — один день у сервера и браузера.
 *
 * Сегодняшний день календарь отмечает в разметке (`aria-current`,
 * `data-today`), а без значения ставит на него и остановку Tab, — и разметка
 * сервера от него зависит. Поэтому часы сервера и браузера стоят на одном
 * моменте — полдень UTC субботы 2026-09-26, как в тестах ядра, — а пояс
 * календаря на странице — UTC (`timeZone`): день не зависит от пояса машины.
 *
 * Часы ставят двое, а момент у обоих отсюда: браузеру — хуки спека дат
 * (`vi.useFakeTimers`, на каждый тест), серверу — `server.ts`, на время
 * рисования страниц дат. Поэтому модуль — без `vitest`: сервер рисует вне
 * воркера прогона, и `vi` там нет.
 */

