/**
 * «Сегодня» прогона гидратации — один день у сервера и браузера.
 *
 * Сегодняшний день календарь отмечает в разметке (`aria-current`,
 * `data-today`), а без значения ставит на него и остановку Tab, — и фикстура
 * сервера от него зависит. Поэтому оба прогона ставят часы на один момент —
 * полдень UTC субботы 2026-09-26, как в тестах ядра, — а пояс календаря на
 * странице — UTC (`timeZone`): день не зависит от пояса машины. Часы ставит
 * хук, который заводит сам спек (`useToday()`), — на каждый тест, а после
 * теста они снова настоящие.
 */

import { afterEach, beforeEach, vi } from 'vitest'

/** Сегодня — полдень UTC 2026-09-26. */
const TODAY = new Date(Date.UTC(2026, 8, 26, 12))

/** Поставить часы на `TODAY` на каждый тест спека. */
export function useToday(): void {
	beforeEach(() => {
		vi.useFakeTimers({ toFake: ['Date'] })
		vi.setSystemTime(TODAY)
	})

	afterEach(() => {
		vi.useRealTimers()
	})
}
