/**
 * Слой лифта — значения, которые компонент получает от предков: неизменяемая
 * карта «ключ → значение».
 *
 * Контекст React один на все ключи, а не по контексту на ключ: сборка читает
 * лифт (`up()`) и при повторной установке эффекта, где хуков нет, — значит,
 * слой обязан быть у неё на руках целиком. Компонент видит его на рендере
 * (`useContext` в `useAdapterContext`) и отдаёт сборке.
 *
 * Детям уходит слой компонента — родительский плюс то, что сборка опустила
 * (`down()`). Отдаёт его `Elevate`. Слой неизменяем: новое значение — новая
 * карта, иначе потребители контекста не узнали бы о смене.
 */

import { createContext } from 'react'

export type TElevatorLayer = ReadonlyMap<symbol, unknown>

/** Слой вне любого владельца: ни одного значения. */
const EMPTY_LAYER: TElevatorLayer = new Map()

export const ElevatorContext = createContext<TElevatorLayer>(EMPTY_LAYER)
