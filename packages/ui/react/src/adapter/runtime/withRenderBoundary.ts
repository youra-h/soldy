/**
 * withRenderBoundary — граница перерисовки: компонент под ней родитель
 * перерисовывает, только когда сменился хоть один его проп по идентичности.
 * Своё состояние — связка компонента (`useAdapter`), слой лифта, локаль —
 * перерисовывает его как обычно: граница режет только перерисовку сверху.
 *
 * Зачем. React перерисовывает компонент вместе с родителем, даже когда пропсы
 * те же. Обычно это дёшево, но таблица перерисовывается на каждый выбор — счёт
 * выбора её состояние — и рисовала бы заново все строки, а строки — все свои
 * ячейки, со слотом `cell` на каждую: «выбрать все» на тысячах строк. Во Vue
 * такая граница — сам компонент: его шаблон перерисовывается по своим
 * зависимостям, а не вместе с родителем.
 *
 * Почему в адаптере. Граница — механизм React (`memo`), а механизмы
 * фреймворка живут только в адаптерном слое (AGENTS.md, «Механизмы фреймворка
 * — только в адаптерном слое»). Компонент встаёт под границу этой обёрткой, а
 * не зовёт `memo` сам: значения из `react` компонентам запрещает блок eslint
 * `soldy/react-components-no-framework`.
 *
 * Сравнение — поверхностное, по идентичности, своего правила нет. Поэтому
 * граница держит, только пока родитель отдаёт те же объекты: значение из
 * состояния связки остаётся тем же объектом, пока не сменилось по содержимому
 * (`TStableSnapshot` — сверка там, один раз на новый снимок связки), слот —
 * тем, что пришёл сверху, как есть. Новый объект на каждый рендер — `?? []`,
 * спред, стрелка-обёртка слота — отключает границу молча: компонент
 * перерисовывается, как без неё. Сравнения пропсов по содержимому здесь нет
 * намеренно: оно обходило бы пропсы на каждый рендер родителя и прятало бы
 * новый объект там, где его надо убрать.
 */

import { memo } from 'react'
import type { FunctionComponent, NamedExoticComponent } from 'react'

export function withRenderBoundary<TProps extends object>(
	component: FunctionComponent<TProps>,
): NamedExoticComponent<TProps> {
	return memo(component)
}
