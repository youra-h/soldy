/**
 * TEventCallbacks — приёмник событий связки: событие уходит колбэку-пропу с
 * тем же именем (`onActionPress`, `onChangeValue`) из пропсов последнего
 * рендера.
 *
 * Связке приёмник отдаётся один раз на её срок (`binding.events.listen` в
 * эффекте с зависимостью от связки), а колбэки потребитель вправе менять на
 * каждом рендере. Поэтому приёмник берёт колбэк не из пропсов, с которыми его
 * отдали, а из последних: их сообщает рендер (`update`).
 *
 * Классом, а не замыканием в `useAdapter`. Приёмник живёт всё монтирование:
 * его держат список приёмников связки и отписка, которую React хранит
 * очисткой эффекта, — а эффект с устойчивыми зависимостями хранит очистку
 * первого коммита (`inst` эффекта у React общий для всех рендеров).
 * Замыкание держит всю область вызова, где его создали: V8 заводит одну
 * область на все замыкания вызова, и в области хука лежат пропсы рендера —
 * их ловит эффект входов. Так таблица держала до размонтирования список строк
 * первого рендера со всеми записями (BENCHMARKS.md, «React, пропсы первого
 * рендера в функциях адаптера»). Стрелка в поле класса держит только `this`,
 * а объект — пропсы последнего рендера.
 *
 * И не функцией модуля, которая собирает замыкание: функцию, которую зовут
 * один раз, минификатор потребителя вправе встроить обратно в тело хука
 * (Terser, `reduce_funcs` — по умолчанию в webpack), и область вернулась бы.
 * Класс в чужую область Terser не переносит.
 *
 * Сторож — `ui/react/__tests__/first-render-props.spec.tsx`.
 */

import type { TEventSink } from '@soldy-ui/setup'

export class TEventCallbacks {
	/** Пропсы последнего рендера: в них колбэки событий. */
	private _props: object = {}

	/** Пропсы рендера: следующее событие уходит колбэку из них. */
	update(props: object): void {
		this._props = props
	}

	/** Приёмник для `binding.events.listen`: событие — колбэку-пропу с тем же именем. */
	readonly sink: TEventSink = (name, args) => {
		const callback: unknown = Reflect.get(this._props, name)

		if (typeof callback === 'function') callback(...args)
	}
}
