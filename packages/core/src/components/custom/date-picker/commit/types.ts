/**
 * Что политика фиксации делает с DatePicker — три команды. Когда их звать,
 * решает политика, а что они делают — DatePicker: правило «выбор закончен —
 * закрыть» и запись значения на сторону остаются у него.
 */
export interface IDatePickerCommitHost {
	/** Значение календаря — в значение DatePicker, как правка любой стороны */
	accept(): void
	/** Значение DatePicker — календарю: правка, которую не приняли, сброшена */
	reset(): void
	/**
	 * Выбор пользователя закончен — панель закрывается, если велит
	 * `closeOnSelect`, а в диапазоне — вторым днём, когда якоря уже нет
	 */
	closeAfterChoice(): void
}

/**
 * Политика фиксации значения — стратегия DatePicker, как поля режима: что
 * правка календаря, выбор пользователя и закрытие панели делают со значением.
 * Её меняет сеттер `confirmable`, и веток по нему в обработчиках DatePicker
 * нет.
 *
 * Значения стратегия не хранит: черновик — значение самого календаря, а
 * значение — DatePicker'а.
 */
export interface IDatePickerCommit {
	/** Календарь поправили — выбором пользователя или командой его расширений */
	edit(): void
	/** Пользователь выбрал день: значение и якорь календаря уже на месте */
	choose(): void
	/** Панель закрылась — любым путём */
	close(): void
}
