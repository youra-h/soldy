import TButton from './button.class'

/**
 * Кнопка, чью роль и остановку Tab пишет владелец, — строка элемента
 * коллекции, который сам знает, что он такое: тег — `listitem`, с выбором —
 * `option`, элемент ListBox и опция Select — `option`, пункт меню — `menuitem`
 * и его виды.
 *
 * По устройству это `TButton`: блок `so-button`, слоты, размер, вид, `press`
 * плагина действия. Своё у неё одно — `role` и `tabindex` она себе не пишет
 * ни на каком теге. `TButton` на ненативном теге объявляет себя кнопкой и
 * остановкой Tab, и владельцу оставалось перекрывать это своим набором:
 * `tabindex="-1"` снимал остановку, но фокус от клика узел всё равно
 * принимал, хотя делать ему нечего. Здесь этих атрибутов нет, пока их не
 * написал владелец — своим набором `aria` на том же узле: роль — элемент,
 * остановку — его коллекция. `aria-disabled` остаётся кнопки: это одно
 * состояние одного узла, посчитанное по одному правилу (`TControl`).
 *
 * Создаёт её владелец при первом чтении своей строки (`row`) — элемент,
 * которого никто не рисует, строки не держит, — и ведёт то, что рисует
 * строка: пишет ей свои `size`, `disabled` и, что у элемента есть, `variant`,
 * `view` и `direction`. Пишут их подписки владельца на свои смены, заведённые
 * в его конструкторе, а не при первом чтении: читает строку монтирование, а
 * элемент живёт дольше него, и снятое монтирование не должно оставлять на нём
 * подписок. Разметка отдаёт строку кнопке целиком (`<Button :ctrl="row">`),
 * как Select — своё поле (`<Input :ctrl="field">`).
 */
export default class TItemRow extends TButton {
	/** Роль и остановку Tab узла пишет владелец, а не кнопка. */
	protected override _syncButtonAria(): void {}
}
