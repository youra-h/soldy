import type { TClasses } from '../../../common'

/**
 * Перетаскивание значения — **только контракт**, класса в этой папке нет.
 *
 * «Тянем — меняем значение» делится на три части, и ни одна не знает о виде
 * компонента:
 *
 * - шкала (`IScale`, `common/scale`) — границы, шаг, перевод между значением
 *   и долей хода; чистая математика;
 * - владелец (`ISlidable`, здесь) — значения ручек и команды жеста: что
 *   сделать со значением, когда указатель нажали, повели, отпустили, а
 *   клавиша сдвинула ручку;
 * - плагины указателя и клавиатуры (`@soldy-ui/plugins`, `custom/slide`) —
 *   операции над DOM: замер дорожки, перевод точки указателя в долю хода,
 *   щелчок к меткам, клавиши, фокус. С владельцем они говорят только через
 *   этот контракт.
 *
 * Первый владелец — `TSlider`. Следующий компонент, где значение задают
 * перетаскиванием, реализует тот же контракт и получает плагины готовыми.
 * Общего класса жеста нет: второго потребителя пока нет, и угадывать, что у
 * них общего сверх контракта, дороже, чем поднять потом.
 */

/** Ось хода: вдоль строки или снизу вверх. */
export type TSlideOrientation = 'horizontal' | 'vertical'

/** Край хода ручки: `start` — к меньшим значениям, `end` — к большим. */
export type TSlideEdge = 'start' | 'end'

/**
 * Щелчок — как метки притягивают ручку, которую тянут указателем. Метку трудно
 * поймать плавной ручкой: она проскакивает, особенно при мелком шаге.
 *
 * Опорные точки — показанные метки владельца: без меток режим ничего не
 * делает. Клавиатура ходит по шагу при любом режиме. Что делает режим, решает
 * стратегия плагина указателя — значение тут только выбирает её.
 *
 * - `none` — ручка идёт за указателем;
 * - `magnet` — притяжение: в радиусе метки ручка стоит на ней;
 * - `plateau` — плато: метка занимает два радиуса хода указателя, а промежутки
 *   между метками сжаты — недостижимых значений нет;
 * - `settle` — доводка: ручка идёт за указателем, а отпущенная в радиусе метки
 *   доезжает до неё;
 * - `hold` — задержка: ручка, пересёкшая метку, стоит на ней, пока не выйдет
 *   время, и потом догоняет указатель.
 */
export type TSlideSnap = 'none' | 'magnet' | 'plateau' | 'settle' | 'hold'

/**
 * Подписка на владельца — только то, что слушают плагины перетаскивания:
 * смена режима щелчка переключает стратегию указателя.
 *
 * Вид подписки, а не `TEvented`: карта событий у владельца своя и шире этой, а
 * `TEvented` по карте инвариантен (AGENTS.md, «События item-адаптера»). Шина
 * владельца подходит сюда структурно.
 */
export interface ISlideEvents {
	on(event: 'change:snap', handler: (value: TSlideSnap) => void): void
	off(event: 'change:snap', handler: (value: TSlideSnap) => void): void
}

/**
 * Владелец перетаскивания — то, что плагинам указателя и клавиатуры нужно от
 * компонента.
 *
 * **Доля хода** в командах — от 0 у `min` до 1 у `max`, уже в направлении
 * роста: плагин переводит в неё точку указателя с учётом оси, вычисленного
 * направления письма и `inverted`, и владелец её не переворачивает.
 *
 * **Жест** — нажатие, протяжка и отпускание одного указателя. Начинают его
 * `grab` (нажали на ручку) или `press` (нажали мимо), ведёт `drag`,
 * заканчивает `release`. Клавиатура жеста не начинает: `shift` и
 * `moveToEdge` — законченные действия.
 *
 * **Части** плагины находят по классам владельца: дорожка — `__track`
 * (её коробка — ход центров ручек, 0 и 1 доли — её края по оси), ручка —
 * `__thumb` (i-я по порядку — ручка i), поле ручки — `input` внутри неё.
 *
 * **Щелчок** (`snap`) решает плагин указателя: где метки и ручки, владелец
 * отдаёт долями хода (`snapPoints`, `fractions`), а плагин переводит в доли
 * радиус щелчка по длине дорожки и выбирает, где встать ручке.
 */
export interface ISlidable {
	/** Классы владельца: по ним плагины находят дорожку и ручки */
	readonly classes: TClasses
	/** Смена режима щелчка — по ней плагин указателя переключает стратегию */
	readonly events: ISlideEvents
	/** Ось хода */
	readonly orientation: TSlideOrientation
	/** Значение растёт в обратную сторону: справа налево или сверху вниз */
	readonly inverted: boolean
	/** Сколько шагов в крупном шаге: Shift со стрелкой, PageUp и PageDown */
	readonly largeStep: number
	/** Значения ручек по возрастанию — списком при любой форме значения владельца */
	readonly values: readonly number[]
	/**
	 * Доли хода ручек, по порядку ручек — в направлении роста, как доли команд.
	 * Не позиции на экране: те владелец раскладывает сам, с `inverted`.
	 */
	readonly fractions: readonly number[]
	/** Как метки притягивают ручку, которую тянут указателем */
	readonly snap: TSlideSnap
	/**
	 * Радиус щелчка в px вдоль оси. Промах по метке — физическая трудность,
	 * поэтому пиксели, а не доля хода: на узком ползунке доля сжалась бы до
	 * пикселя. В долю его переводит плагин по длине дорожки.
	 */
	readonly snapRadius: number
	/**
	 * Точки щелчка — доли хода показанных меток, в направлении роста, по
	 * возрастанию и без повторов. Меток нет — пусто, и щелчку не к чему
	 * притягивать.
	 */
	readonly snapPoints: readonly number[]
	/**
	 * Ручка, которую ведёт жест; вне жеста — `undefined`. Бывает, что до
	 * первого движения она предварительная: у ручек на одном значении какую
	 * тянуть, решает направление движения.
	 */
	readonly activeThumb: number | undefined
	/**
	 * Нажали на ручку `index` в точке `fraction`. Значение не меняется: ручка
	 * запоминает смещение захвата и дальше идёт за указателем с ним.
	 *
	 * @returns начался ли жест — у выключенного владельца и несуществующей
	 * ручки нет
	 */
	grab(index: number, fraction: number): boolean
	/**
	 * Нажали мимо ручек в точке `fraction`: ближайшая ручка встаёт туда.
	 *
	 * @returns начался ли жест — у выключенного владельца и без ручек нет
	 */
	press(fraction: number): boolean
	/**
	 * Указатель жеста в точке `fraction`. Вне жеста ничего не делает.
	 *
	 * Щелчок плагин выражает этой же командой: отдаёт долю, в которой
	 * указатель поставил бы ручку туда, куда её притянула метка.
	 */
	drag(fraction: number): void
	/** Жест закончен: указатель отпустили или браузер его отнял */
	release(): void
	/**
	 * Жест закончен доводкой: ручка жеста встаёт в долю хода `fraction` — уже
	 * не перетаскиванием, и переход темы её довозит. `commit` — один на жест, с
	 * доведённым значением. Вне жеста ничего не делает.
	 */
	settle(fraction: number): void
	/**
	 * Сдвинуть ручку `index` на `count` шагов шкалы: к `max` — плюс, к `min` —
	 * минус. Не `step`: у владельца так обычно зовётся сам шаг шкалы
	 */
	shift(index: number, count: number): void
	/** Поставить ручку `index` на край её хода */
	moveToEdge(index: number, edge: TSlideEdge): void
}
