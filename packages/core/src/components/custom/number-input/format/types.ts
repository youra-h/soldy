/**
 * Формат поля числа в локали и опциях: текст числа, его разбор и правило
 * набора — один объект на тег и опции.
 *
 * Текст — строка `Intl.NumberFormat` целиком: «1 234,5», «12 %»,
 * «1 234,50 ₽», «5 кг». Своих частей у валюты, процента и единицы нет, и разбор
 * снимает их с текста так же, как пробелы и метки направления.
 */
export interface INumberFormat {
	/** Число строкой формата; нет числа — пусто */
	format(value: number | undefined): string
	/**
	 * Число из текста: цифры локали, ASCII и полноширинные; разделители групп
	 * и пробелы пропускаются; десятичный разделитель — локали, и точка, если
	 * она не разделитель групп; знак — минус (ASCII, U+2212, локали) или плюс
	 * в начале; валюта, процент, единица и метки направления снимаются. У
	 * процента — делённое на 100. Цифр нет или текст не число — `undefined`
	 */
	parse(text: string): number | undefined
	/**
	 * Годится ли текст для набора — частичное число: то, что `parse` читает, и
	 * то, что ещё допишут (`-`, пусто). Минус — только `signed`, десятичный
	 * разделитель — только у формата с дробью (`fraction`)
	 */
	accepts(text: string, signed: boolean): boolean
	/** Формат даёт дробь: десятичный разделитель набирается, клавиатура — с ним */
	readonly fraction: boolean
	/**
	 * Направление числа в формате — по первому сильному знаку его строки:
	 * `he-IL` с валютой и `fa-IR` с единицей пишут справа налево, `ru-RU` —
	 * слева направо. От него порядок знака, валюты и единицы в строке
	 */
	readonly direction: 'ltr' | 'rtl'
	/** Язык формата — глифы и шейпинг числа по нему, а не по языку страницы */
	readonly lang: string
}

/**
 * Знаки числа в локали: из чего разбор собирает число и что он снимает.
 * Множества — уже без пробелов и меток направления: разбор снимает их с
 * текста первыми.
 */
export type TNumberSymbols = {
	/** Цифры системы счисления — по знаку на цифру */
	readonly digits: readonly string[]
	/** Минусы: ASCII, U+2212 и минус локали */
	readonly minus: ReadonlySet<string>
	/** Плюсы: ASCII и плюс локали */
	readonly plus: ReadonlySet<string>
	/** Десятичный разделитель локали и точка, если она не разделитель групп */
	readonly decimal: ReadonlySet<string>
	/** Разделитель групп локали */
	readonly group: ReadonlySet<string>
	/**
	 * Литералы формата — валюта, процент, единица во всех формах числа, без
	 * пробелов и меток направления. Длинные — первыми: «километров» снимается
	 * раньше «километр»
	 */
	readonly literals: readonly string[]
}

/**
 * Число, прочитанное из текста: знак и цифры ASCII. Дробной части нет —
 * `undefined`; есть разделитель без цифр — пустая строка.
 */
export type TNumberReading = {
	readonly sign: '' | '-' | '+'
	readonly integer: string
	readonly fraction: string | undefined
}
