/**
 * Ширина колонки таблицы — общее у колонки и у раскладки колонок: ширина по
 * умолчанию, пределы ручки и прижатие к границам. Колонка по ним считает итог
 * и ход ручки, расширение колонок — ширины гибких колонок, и формула у них
 * одна.
 */

/**
 * Ширина по умолчанию, px, — у колонки без своей ширины. От неё раскладка
 * считает гибкую колонку: в `none` колонка стоит в ней, в `auto` растёт от
 * неё. Около двадцати знаков текста — столько же давала распорка в заголовке
 * темы.
 */
export const COLUMN_WIDTH = 160

/**
 * Пределы ручки ширины, px, — когда своих границ у колонки нет.
 *
 * Ручке нужен ход: её поле — `input type="range"` с `min` и `max`, а Home и End
 * ведут к его краям. Уже нижнего предела колонка перестаёт быть колонкой: в
 * ней не остаётся места ни подписи, ни ручке у её края — поэтому до него и
 * сжимает колонку без `minWidth` раскладка `contain`. Верхний — заведомо шире
 * любой осмысленной колонки, но конечный: End не уводит ширину в
 * бесконечность. Своё место у колонки потребитель задаёт границами.
 */
export const RESIZE_MIN = 48
export const RESIZE_MAX = 1600

/**
 * Ширина в границах. Нижняя граница сильнее верхней, как `min-width` в CSS:
 * при `minWidth` больше `maxWidth` итог — `minWidth`. Ширины нет — нет и итога.
 */
export function clampWidth(
	width: number | undefined,
	min: number | undefined,
	max: number | undefined,
): number | undefined {
	if (width === undefined) return undefined

	const capped = max === undefined ? width : Math.min(width, max)

	return min === undefined ? capped : Math.max(capped, min)
}
