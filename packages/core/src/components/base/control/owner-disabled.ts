import type { IDisabledItem, IDisabledOwner } from './types'

/**
 * «Выключено» элемента, которым владеет компонент (список, набор табов):
 * элемент выключен, если выключен сам **или** выключен владелец — как
 * `<fieldset disabled>` в HTML. Правило одно на все коллекции и живёт только
 * здесь; расширения зовут эти две функции и `item.disabled` не пишут.
 *
 * При «или» не нужно отличать «не задавали» от `false`: `false` значит «сам
 * себя не выключает», и включение владельца не включит элемент, выключенный
 * сам по себе.
 *
 * Своё значение не копируется: оно уже лежит в `rawValue`, куда его пишут
 * фабрика, разметка и `batch.patch` через сеттер. Итог отдаёт резольвер,
 * поэтому всё, что читает `item.disabled`, получает его без правок.
 *
 * О коллекции модуль не знает — элементы передаёт расширение.
 */

/**
 * Привязать `disabled` элемента к владельцу.
 *
 * Зовётся на каждом добавлении, в том числе повторно для того же элемента:
 * резольвер заменяется, а `change` приходит, только если итог сменился.
 */
export function bindDisabledToOwner(item: IDisabledItem, owner: IDisabledOwner): void {
	item.states.disabled.setResolver((own) => own || owner.disabled)
}

/**
 * Владелец сменил `disabled` — сообщить элементам, у которых сменился итог.
 *
 * Это только элементы со своим `false`: у выключенных самих по себе итог
 * `true` при любом владельце, и событие было бы ложным.
 *
 * Прежний итог таких элементов противоположен нынешнему: он равен прежнему
 * `disabled` владельца, а тот только что сменился. Своего значения владельца
 * функция не получает — `change:disabled` несёт одно новое значение.
 */
export function notifyOwnerDisabled(items: Iterable<IDisabledItem>): void {
	for (const item of items) {
		const state = item.states.disabled

		if (!state.rawValue) state.notify(!state.value)
	}
}
