/**
 * Дата календаря — строка `YYYY-MM-DD`, как `value` у `<input type="date">`:
 * год четырьмя цифрами, от `0001` до `9999`, месяц и день — двумя. Ни
 * времени, ни часового пояса в ней нет.
 *
 * Строка, а не объект (`Date`, `CalendarDate`, `Temporal.PlainDate`). Её
 * одинаково сверяют правило «то же самое» ядра и обмена, она переживает
 * снимок `valueOf()` и серверный рендер, а порядок строк совпадает с порядком
 * дат. Объект обмен сверял бы по идентичности, и дата, собранная заново на
 * каждом рендере, считалась бы новым значением. `Date` вдобавок изменяемый и
 * несёт часовой пояс.
 *
 * Псевдоним `string`, а не шаблонный тип: строку из разметки пришлось бы
 * приводить. Формат проверяет разбор — `parseDate`.
 */
export type TCalendarDate = string

/** День недели: 0 — воскресенье … 6 — суббота, как у `Date#getUTCDay()`. */
export type TWeekday = 0 | 1 | 2 | 3 | 4 | 5 | 6

/**
 * Единица сдвига даты. Неделя — семь дней; месяц и год прижимают число к
 * длине месяца: 31 января плюс месяц — последнее число февраля.
 */
export type TDateUnit = 'day' | 'week' | 'month' | 'year'

/** День сетки месяца. */
export type TMonthGridDay = {
	/** Дата дня */
	date: TCalendarDate
	/** День соседнего месяца: им сетка добирает неделю до целой */
	outside: boolean
}

/** Ширина имени дня недели: короткое — подпись колонки, полное — для скринридера. */
export type TWeekdayWidth = 'short' | 'long'

/**
 * Всё, что календарь берёт у локали: подписи. Один объект на тег локали —
 * его форматтеры создаются при первом обращении и живут, пока жив модуль.
 * Первый день недели от локали не зависит: он у календаря, `weekStart`.
 *
 * Подписи — в календаре локали, если месяцы у него григорианские (`gregory`,
 * `buddhist`, `japanese`, `roc`): у `th-TH` год буддийский, 2569. У остальных
 * (`persian`, `islamic-*`, `hebrew`) месяцы не совпадают с сеткой, и подписи
 * григорианские: своей арифметики этих календарей у ядра нет. Даты всегда
 * форматируются в `UTC` — полночь даты и есть её день.
 */
export interface ICalendarLocale {
	/** Канонический тег локали; невалидный — умолчание `en-US` */
	readonly locale: string
	/** Календарь подписей */
	readonly calendar: string
	/** Заголовок месяца даты: месяц и год */
	monthTitle(date: TCalendarDate): string
	/** Номер дня в цифрах локали — без слов вокруг него (у `ja-JP` без «日») */
	dayNumber(date: TCalendarDate): string
	/** Полная дата с днём недели — доступное имя дня */
	fullDate(date: TCalendarDate): string
	/** Имя дня недели */
	weekdayName(day: TWeekday, width: TWeekdayWidth): string
}
