/**
 * Знак шириной в букву: буква (`L`), цифра (`N`) и протяжённый знак (`Mc`).
 *
 * Протяжённые гласные и анусвара индийских письменностей стоят в строке рядом
 * с буквой и занимают место, как она: в «ஞாயி.» и «మంగళ» таких знаков по
 * четыре. Точка сокращения, пробел, знаки над и под буквой (`Mn`, `Me`) и
 * невидимые (`Cf`) не считаются: «lun.» и «मंगल» — по три.
 */
const LETTER = /[\p{L}\p{N}\p{Mc}]/u

/**
 * Сколько знаков шириной в букву вмещает подпись колонки. Колонка календаря —
 * около трёх кеглей подписи, и при пороге 4 короткими стали бы «ஞாயி.»,
 * «మంగళ» и «ಮಂಗಳ», которые шире колонки на мелком размере.
 */
const MAX_LETTERS = 3

/**
 * Форма подписи колонки дня недели — одна на всю неделю локали: короткое имя
 * (`weekday: 'short'`), если у всех семи коротких имён не больше трёх знаков
 * шириной в букву, иначе узкое (`'narrow'`).
 *
 * Короткое различимо — «пн», «Mon», «lun.», «周一», — а узкое у части языков
 * повторяется: у `ru` понедельник и пятница — «П», вторник и воскресенье —
 * «В». Но у других короткое — целое слово («الخميس», «വെള്ളി»), и колонке его
 * не вместить. Решение — по неделе, а не по дню: смешанная шапка хуже любой
 * из форм.
 *
 * Правило — по знакам имени, а не по его ширине в разметке и не по списку
 * локалей: ядро разметки не знает, а язык, которого в списке нет, остался бы
 * без правила. И не по графемам (`Intl.Segmenter`): «ஞாயி.», «మంగళ», «ಮಂಗಳ» —
 * по три графемы и шире колонки, а границы графем индийских письменностей
 * менялись в Unicode 15.1, и сервер с браузером могли бы решить по-разному.
 *
 * @param names короткие имена дней недели — все семь
 */
export function weekdayLabelWidth(names: readonly string[]): 'short' | 'narrow' {
	return names.every((name) => letterCount(name) <= MAX_LETTERS) ? 'short' : 'narrow'
}

/** Число знаков шириной в букву — по код-пойнтам, а не по кодовым единицам строки. */
function letterCount(name: string): number {
	return [...name].filter((char) => LETTER.test(char)).length
}
