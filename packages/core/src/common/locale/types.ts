/**
 * Строка, в которую входит имя части: «Close Настройки», «Clear Город».
 *
 * Функция, а не слово, к которому библиотека дописывает имя: порядок слов у
 * каждого языка свой, и склейка «слово + имя» навязала бы всем один. Имя
 * приходит без пробелов по краям; пустое — имени у части нет, и что тогда
 * сказать, решает сама функция.
 */
export type TNamedText = (name: string) => string

/**
 * Словарь строк, которые библиотека рисует сама: имена кнопок без текста —
 * закрытия, листания, очистки, — и полей, которым подпись неоткуда взять.
 *
 * Разделы — по компоненту, который читает строку. Имён, которые знает только
 * приложение (подпись поля, имя индикатора выполнения), в словаре нет: их
 * задают пропсы компонента (`aria_label`, `thumbLabels`).
 *
 * Умолчание — английское (`DEFAULT_TRANSLATIONS`), а свои строки приложение
 * накладывает поверх него в точке входа (`useTranslations` из
 * `@soldy-ui/plugins`).
 */
export type TTranslations = {
	/** Модальный слой — окно и выезжающая панель */
	readonly modal: {
		/** Имя кнопки закрытия */
		readonly close: string
	}
	/** Модальное окно */
	readonly dialog: {
		/** Имя кнопки разворота — одно на оба состояния: состояние сообщает `aria-pressed` */
		readonly maximize: string
	}
	/** Поповер */
	readonly popover: {
		/** Имя кнопки закрытия */
		readonly close: string
	}
	/** Табы */
	readonly tabs: {
		/** Имя кнопки закрытия таба — с текстом таба */
		readonly close: TNamedText
	}
	/** Теги */
	readonly tags: {
		/** Имя кнопки закрытия тега — с текстом тега */
		readonly close: TNamedText
		/** Имя кнопки «…» — той, что открывает панель с непоместившимися тегами */
		readonly more: string
	}
	/** Лента с кнопками листания */
	readonly scroller: {
		/** Имя кнопки «назад» */
		readonly prev: string
		/** Имя кнопки «вперёд» */
		readonly next: string
	}
	/** Поле ввода — текстовое и поле даты */
	readonly field: {
		/** Имя кнопки очистки — с именем поля */
		readonly clear: TNamedText
	}
	/** Таблица */
	readonly table: {
		/** Имя чекбокса «выбрать все» в шапке колонки выбора */
		readonly selectAll: string
	}
	/** Календарь */
	readonly calendar: {
		/** Имя кнопки «предыдущий месяц» */
		readonly prevMonth: string
		/** Имя кнопки «следующий месяц» */
		readonly nextMonth: string
		/** Имя стрелки панели выбора месяца и года «предыдущий год» — на уровне месяцев */
		readonly prevYear: string
		/** Имя стрелки «следующий год» — на уровне месяцев */
		readonly nextYear: string
		/** Имя стрелки «предыдущие 12 лет» — на уровне лет */
		readonly prevYears: string
		/** Имя стрелки «следующие 12 лет» — на уровне лет */
		readonly nextYears: string
	}
	/** Поле даты с календарём в панели */
	readonly datePicker: {
		/** Имя кнопки календаря — оно же имя панели, которую кнопка открывает */
		readonly trigger: string
		/** Имя поля начала диапазона */
		readonly start: string
		/** Имя поля конца диапазона */
		readonly end: string
	}
}

/**
 * Часть словаря: любые разделы, в разделе — любые строки. Чего в части нет,
 * остаётся от того, на что её накладывают.
 */
export type TPartialTranslations = {
	readonly [K in keyof TTranslations]?: Partial<TTranslations[K]>
}

/**
 * Компонент, который берёт строки из словаря.
 *
 * Словарь — весь, а не свой раздел: какой раздел читать, знает класс, и
 * владелец словаря (плагин словаря) пишет один и тот же объект любому
 * компоненту. Пропом словарь не задаётся и в разметку не уходит: разметка
 * получает готовые имена — выходы компонента.
 */
export interface ITranslatable {
	/**
	 * Словарь строк библиотеки; по умолчанию английский (`DEFAULT_TRANSLATIONS`).
	 * При монтировании его пишет плагин словаря — словарь приложения, — и он же
	 * пишет новый на каждую его смену. Без setup словарь задаёт код
	 */
	translations: TTranslations
}

export type TTranslatableEvents = {
	/**
	 * change:translations — словарь сменился. Имена, собранные из него, к
	 * событию уже новые
	 */
	'change:translations': (value: TTranslations) => void
}
