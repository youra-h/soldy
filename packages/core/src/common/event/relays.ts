/**
 * TRelays — пробросы событий в эмиттер из его источников (`relay` и
 * `relayAll` у `TEvented`).
 *
 * Проброс — это подписка эмиттера на источник. Подписан он, только пока
 * эмиттер слушают: первый подписчик эмиттера подписывает его пробросы на
 * источники, ушедший последний — отписывает. Поэтому эмиттер, который живёт
 * меньше источника (фасад коллекции над движком снаружи), на нём не остаётся:
 * он уходит вместе со своими подписчиками, а они отписываются сами. Цепочка
 * (расширение → item-адаптер → фасад) подписывается и отписывается так же:
 * подписка эмиттера на источник для источника — тоже подписчик.
 *
 * Слушают ли эмиттер, знает только он сам, поэтому сообщает об этом он —
 * вызовами `subscribe()` и `unsubscribe()`.
 */
export class TRelays {
	/** Пробросы: каждый подписывает эмиттер на свой источник и возвращает отписку. */
	private readonly _relays: (() => () => void)[] = []

	/** Отписки от источников — пока пробросы подписаны. */
	private _unsubscribes: (() => void)[] = []

	/** Подписаны ли пробросы на источники, то есть слушают ли эмиттер. */
	private _subscribed = false

	/** Новый проброс. Эмиттер уже слушают — подписывается сразу. */
	add(relay: () => () => void): void {
		this._relays.push(relay)

		if (this._subscribed) this._unsubscribes.push(relay())
	}

	/** Эмиттер начали слушать: подписать пробросы на источники. */
	subscribe(): void {
		if (this._subscribed) return

		this._subscribed = true
		this._unsubscribes = this._relays.map((relay) => relay())
	}

	/** Эмиттер перестали слушать: отписать пробросы от источников. */
	unsubscribe(): void {
		if (!this._subscribed) return

		this._subscribed = false

		for (const unsubscribe of this._unsubscribes.splice(0)) unsubscribe()
	}

	/** Отписать пробросы и забыть их. */
	destroy(): void {
		this.unsubscribe()
		this._relays.splice(0)
	}
}
