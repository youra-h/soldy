/**
 * Шкала хода: границы, шаг и перевод между значением и долей хода.
 *
 * Чистая математика — без событий и без знания о компоненте. Её берёт всякий,
 * кто задаёт значение перетаскиванием: ползунок сегодня, следующий такой
 * компонент — завтра. Перетаскивание (`ISlidable`) говорит долями хода, а
 * значение живёт в единицах шкалы; переводит одно в другое только она.
 *
 * Доля хода — от 0 у `min` до 1 у `max`, линейно по значению. Куда на экране
 * растёт значение (RTL, вертикаль, `inverted`), шкала не знает: это решают
 * плагины и разметка.
 */
export interface IScale {
	/** Начало хода — значение у доли 0 */
	readonly min: number
	/** Конец хода — значение у доли 1; не меньше `min` */
	readonly max: number
	/**
	 * Ровный шаг сетки. У шкалы-списка ровного шага нет — `undefined`: соседние
	 * допустимые значения отстоят друг от друга по-разному.
	 */
	readonly interval: number | undefined
	/** Первое достижимое значение */
	readonly first: number
	/**
	 * Последнее достижимое значение. У сетки это её последний узел не дальше
	 * `max`: `max` вне сетки недостижим, как у нативного `input[type=range]`.
	 */
	readonly last: number
	/** Все достижимые значения по возрастанию — точки меток шкалы */
	readonly points: readonly number[]
	/** Ближайшее достижимое значение; поровну от двух — большее, как у нативного поля */
	snap(value: number): number
	/** Доля хода у значения: 0 — `min`, 1 — `max`; за границами — граница */
	fraction(value: number): number
	/** Ближайшее достижимое значение у доли хода */
	valueAt(fraction: number): number
	/**
	 * Значение через `count` шагов от ближайшего достижимого: у сетки шаг —
	 * `interval`, у списка — соседний элемент. За краем — край.
	 */
	shift(value: number, count: number): number
}

/**
 * Опции шкалы. Вид выбирает форма шага: число — ровная сетка от `min`,
 * массив — список допустимых значений (неравный шаг).
 */
export type TScaleOptions = {
	/** Начало хода */
	min: number
	/** Конец хода; меньше `min` — ход схлопывается в `min` */
	max: number
	/** Шаг числом или список допустимых значений */
	step: number | readonly number[]
}
