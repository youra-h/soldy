/**
 * Шкала хода: границы, шаг и перевод между значением и долей хода.
 *
 * Чистая математика — без событий и без знания о компоненте. Её берёт всякий,
 * кто задаёт значение перетаскиванием или шагом: ползунок и оценка, поле
 * числа. Перетаскивание (`ISlidable`) говорит долями хода, а значение живёт в
 * единицах шкалы; переводит одно в другое только она.
 *
 * Доля хода — от 0 у `min` до 1 у `max`, линейно по значению. Куда на экране
 * растёт значение (RTL, вертикаль, `inverted`), шкала не знает: это решают
 * плагины и разметка.
 *
 * Сторона бывает открытой — `min` или `max` бесконечны: у поля числа без
 * границ ход с неё не кончается. Доли у открытой шкалы нет смысла считать, и
 * перетаскивание открытой шкалы не берёт.
 */
export interface IScale {
	/** Начало хода — значение у доли 0; у открытого начала — `-Infinity` */
	readonly min: number
	/** Конец хода — значение у доли 1; не меньше `min`; у открытого конца — `Infinity` */
	readonly max: number
	/**
	 * Ровный шаг сетки. У шкалы-списка ровного шага нет — `undefined`: соседние
	 * допустимые значения отстоят друг от друга по-разному.
	 */
	readonly interval: number | undefined
	/** Первое достижимое значение; у сетки с открытым началом — `-Infinity` */
	readonly first: number
	/**
	 * Последнее достижимое значение. У сетки это её последний узел не дальше
	 * `max`: `max` вне сетки недостижим, как у нативного `input[type=range]`. У
	 * сетки с открытым концом — `Infinity`.
	 */
	readonly last: number
	/**
	 * Все достижимые значения по возрастанию — точки меток шкалы. У сетки с
	 * открытой стороной узлов без конца, и список пуст
	 */
	readonly points: readonly number[]
	/** Ближайшее достижимое значение; поровну от двух — большее, как у нативного поля */
	snap(value: number): number
	/** Доля хода у значения: 0 — `min`, 1 — `max`; за границами — граница */
	fraction(value: number): number
	/** Ближайшее достижимое значение у доли хода */
	valueAt(fraction: number): number
	/**
	 * Значение через `count` шагов в сторону знака `count`: у сетки шаг —
	 * `interval`, у списка — соседний элемент. Первый шаг — к соседнему
	 * достижимому значению с этой стороны: со значения вне сетки — к ближайшему
	 * с неё (с 2,5 при шаге 1 — вверх на 3, вниз на 2), как у нативного поля
	 * числа. С достижимого значения — на `count` шагов. За краем — край.
	 */
	shift(value: number, count: number): number
}

/**
 * Опции шкалы. Вид выбирает форма шага: число — ровная сетка от `min`,
 * массив — список допустимых значений (неравный шаг).
 */
export type TScaleOptions = {
	/** Начало хода; `-Infinity` — открытое начало, сетка тогда — от нуля */
	min: number
	/** Конец хода; меньше `min` — ход схлопывается в `min`; `Infinity` — открытый конец */
	max: number
	/** Шаг числом или список допустимых значений */
	step: number | readonly number[]
}
