import { TAttributes } from '../attributes'

/**
 * Набор атрибутов доступности компонента.
 *
 * Живой объект в `TComponentView`, доступный наследникам, плагинам и
 * расширениям коллекции. Каждый пишет свою часть туда же, а разметка биндит
 * один набор — `v-bind="aria"`.
 *
 * Почему не спред нескольких наборов. Так было раньше, и у элемента таба в
 * одном `v-bind` уже сходились четыре источника: роль от ядра, связка с
 * панелью от расширения, активность от коллекции, имя от плагина. Каждый
 * новый ARIA-паттерн добавлял туда ещё один — собирать это в разметке шести
 * адаптеров невозможно.
 *
 * Механика набора — в `TAttributes`. Своего у ARIA два обстоятельства:
 *
 * - имена пишутся целиком (`aria.add('aria-label', …)`), потому что префикс
 *   здесь не универсален: `role` и `tabindex` живут в этом же наборе, хотя на
 *   `aria-` не начинаются. Без них паттерн не работает — `<div role="button">`
 *   без `tabindex` нельзя сфокусировать, а значит и активировать с клавиатуры;
 * - значения уже строки предметной области (`'true'`, `'false'`, идентификатор),
 *   и приводить их не из чего. Булев `false` для ARIA не то же самое, что
 *   отсутствие атрибута: `aria-selected="false"` — «есть, но не выбрана»,
 *   а без атрибута опция вообще не объявляется выбираемой.
 */
export class TAria extends TAttributes {}
